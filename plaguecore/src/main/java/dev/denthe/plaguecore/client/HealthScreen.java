/**
 * Экран «Состояние здоровья»: человек осматривает сам себя.
 * Спек интерфейса, раздел 7.
 *
 * Экран ничего не решает и ничего не спрашивает у сервера — он рисует
 * то, что собрал {@link HealthSense}. Ни одного числа болезни наружу
 * не выходит: ни заражения, ни стадии, ни порогов.
 *
 * Оформление — полевой лазарет: просмолённый кожаный планшет с
 * латунными уголками, врезкой под фигуру и врезкой под текст. Панель
 * приходит готовой картинкой {@code health_panel.png}, её рисует
 * {@code tools/lazaret-gfx/графика.py}; геометрия ниже обязана
 * совпадать с геометрией в том скрипте.
 */
