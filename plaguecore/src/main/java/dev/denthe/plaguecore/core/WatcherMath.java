package dev.denthe.plaguecore.core;

/**
 * Что Наблюдатель делает прямо сейчас. Спек хоррора, раздел 3.
 *
 * Правило одно: под взглядом он неподвижен, без взгляда — ближе,
 * вплотную — исчезает. Играет это против того, как человек проверяет
 * страх: чтобы убедиться, что там никого нет, надо отвести глаза.
 *
 * Первые явления за сессию всегда кончаются растворением, и только
 * последнее настоящее. Иначе настоящая атака не стоит ничего: игроки
 * должны сначала решить, что он безвреден, и лишь потом ошибиться.
 */
public final class WatcherMath {
    private WatcherMath() {}

    public enum Решение { СТОЯТЬ, ПОДОЙТИ, РАСТВОРИТЬСЯ, НАПАСТЬ }

    /**
     * @param наНегоСмотрят        игрок держит его в поле зрения
     * @param дистанция            сколько блоков между ними
     * @param настоящий            это последнее явление за сессию
     * @param дистанцияРастворения ближе которой фантом исчезает
     */
    public static Решение решение(boolean наНегоСмотрят, double дистанция,
                                  boolean настоящий, double дистанцияРастворения) {
        if (дистанция <= дистанцияРастворения) {
            return настоящий ? Решение.НАПАСТЬ : Решение.РАСТВОРИТЬСЯ;
        }
        return наНегоСмотрят ? Решение.СТОЯТЬ : Решение.ПОДОЙТИ;
    }

    /**
     * Настоящим бывает ровно одно явление — последнее из отпущенных
     * на сессию. Именно равенство, а не «не меньше»: режиссёр сверх
     * лимита не выпускает, но мастер командой может, и с «не меньше»
     * каждое такое явление оказывалось настоящим. В мире, где счётчик
     * выбит проверками, это превращало Наблюдателя в обычного зомби —
     * он бросался с первой же встречи, а после броска у него оживал
     * ванильный ИИ.
     */
    public static boolean настоящий(int былоЯвлений, int лимитЗаСессию) {
        return былоЯвлений == лимитЗаСессию - 1;
    }

    /**
     * Смотрит ли игрок в его сторону. Взгляд задан единичным вектором,
     * цель — смещением от глаз игрока.
     *
     * @param порог косинус половины конуса зрения; 0.5 — примерно 60°
     */
    public static boolean смотрит(double взглядX, double взглядY, double взглядZ,
                                  double наX, double наY, double наZ, double порог) {
        double длина = Math.sqrt(наX * наX + наY * наY + наZ * наZ);
        if (длина < 1e-6) return true;
        double косинус = (взглядX * наX + взглядY * наY + взглядZ * наZ) / длина;
        return косинус > порог;
    }
}
