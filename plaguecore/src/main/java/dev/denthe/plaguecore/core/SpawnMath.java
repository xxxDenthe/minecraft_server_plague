package dev.denthe.plaguecore.core;

/**
 * Перевод «шанса за ночь» в «шанс за один случайный тик блока».
 *
 * Споровый мешок катает кубик не раз за ночь, а на каждом случайном
 * тике — потому что иначе его пришлось бы искать в мире перебором
 * блоков, а мешков в гнилом поле сотни. Случайный тик приходит к блоку
 * сам и только в загруженном чанке, то есть ровно там, где рядом люди.
 *
 * Ценой этого шанс приходится пересчитывать. Один блок за ночь получает
 * примерно {@link #ТИКОВ_ЗА_НОЧЬ} случайных тиков, и «30% за ночь»
 * означает «не выпало ни разу за все семь бросков» с вероятностью 0.7:
 *
 * <pre>
 *   (1 - p)^7.32 = 1 - 0.30   =>   p = 1 - (1 - 0.30)^(1/7.32) ≈ 0.0476
 * </pre>
 *
 * <p>ponytail: число тиков за ночь посчитано под ванильную скорость
 * случайных тиков (3 на секцию). Если на сервере крутить
 * {@code randomTickSpeed}, выводки станут чаще или реже пропорционально —
 * лечится правкой шанса в конфиге, отдельного кода не нужно.
 */
public final class SpawnMath {
    private SpawnMath() {}

    /** Длина ночи в тиках: с 13000 до 23000 игрового времени. */
    public static final int НОЧЬ_ТИКОВ = 10_000;

    /** Ванильная скорость случайных тиков: 3 попытки на секцию 16×16×16. */
    private static final double СКОРОСТЬ_ТИКОВ = 3.0;

    /** Сколько случайных тиков достаётся одному блоку за ночь. */
    public static final double ТИКОВ_ЗА_НОЧЬ = НОЧЬ_ТИКОВ * СКОРОСТЬ_ТИКОВ / 4096.0;

    /**
     * Шанс на один случайный тик, дающий за ночь заданную вероятность.
     *
     * Края обрабатываются честно: 0 — никогда, 1 — на первом же тике.
     */
    public static float шансЗаТик(float заНочь) {
        if (заНочь <= 0f) return 0f;
        if (заНочь >= 1f) return 1f;
        return (float) (1.0 - Math.pow(1.0 - заНочь, 1.0 / ТИКОВ_ЗА_НОЧЬ));
    }

    /**
     * Обратный перевод: во что сложится шанс за тик к концу ночи.
     * Нужен только тестам и отладке — в игре не зовётся.
     */
    public static float заНочь(float шансЗаТик) {
        if (шансЗаТик <= 0f) return 0f;
        if (шансЗаТик >= 1f) return 1f;
        return (float) (1.0 - Math.pow(1.0 - шансЗаТик, ТИКОВ_ЗА_НОЧЬ));
    }
}
