package dev.denthe.plaguecore.core;

/**
 * Разрушение Сердца чумы: сколько кусков уже отвалилось.
 *
 * Считаем из здоровья, а не из числа ударов. Разница видна после
 * перезахода в мир: счётчик ударов пришлось бы хранить и сверять
 * с NBT, а здоровье и так сохраняется — из него всё выводится заново
 * и всегда сходится.
 *
 * Куски отваливаются в заданном порядке: сначала корни, потом ветки,
 * в конце тело. Порядок фиксирован намеренно — владелец выбрал простое
 * разрушение без прицельных хитбоксов, а игроку всё равно не видно,
 * какой кусок «выбран»: он видит, как сердце разваливается снизу вверх.
 */
public final class HeartDecay {
    private HeartDecay() {}

    /**
     * Имена костей модели в порядке отваливания.
     * Индекс в массиве = номер бита в маске.
     */
    public static final String[] КОСТИ = {
        "roots_p1", "roots_p2", "roots_p3", "roots_p4",
        "roots_p5", "roots_p6", "roots_p7", "roots_p8",
        "arteries_p1", "arteries_p2", "arteries_p3", "arteries_p4",
        "body_p1", "body_p2", "body_p3", "body_p4",
        "body_p5", "body_p6", "body_p7", "body_p8",
    };

    /** Сколько всего кусков. Задано моделью, в конфиг не выносится. */
    public static final int КУСКОВ = КОСТИ.length;

    /** Маска целиком осыпавшегося сердца. */
    public static final int ВСЕ_КУСКИ = (1 << КУСКОВ) - 1;

    /** Медленнее этой доли биение не становится даже у полумёртвого сердца. */
    private static final float МЕДЛЕННЕЕ_НЕКУДА = 0.35f;

    /**
     * Битовая маска отвалившихся кусков: бит i поднят — кусок
     * {@code КОСТИ[i]} отвалился.
     *
     * @param здоровье текущее здоровье
     * @param максимум максимальное здоровье; 0 или меньше даёт целое сердце
     */
    public static int маска(float здоровье, float максимум) {
        int отвалилось = Math.round((1f - доляЗдоровья(здоровье, максимум)) * КУСКОВ);
        if (отвалилось <= 0) return 0;
        if (отвалилось >= КУСКОВ) return ВСЕ_КУСКИ;
        return (1 << отвалилось) - 1;
    }

    /**
     * Множитель скорости анимации биения: целое сердце бьётся как
     * задумано, умирающее — заметно медленнее.
     */
    public static float скоростьБиения(float здоровье, float максимум) {
        return МЕДЛЕННЕЕ_НЕКУДА
            + (1f - МЕДЛЕННЕЕ_НЕКУДА) * доляЗдоровья(здоровье, максимум);
    }

    private static float доляЗдоровья(float здоровье, float максимум) {
        if (максимум <= 0f) return 1f;
        float доля = здоровье / максимум;
        return доля < 0f ? 0f : (доля > 1f ? 1f : доля);
    }
}
