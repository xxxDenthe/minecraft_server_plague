package dev.denthe.plaguecore.core;

/**
 * Математика Пограничья — зоны между городом и Гнилью.
 *
 * Своей разметки у зоны нет и не заводится: «Пограничье» — это просто
 * чанки уровня 1..3 в той же сетке чумы, по которой уже работает всё
 * остальное. Поэтому зона сама переползает к городу вместе с заразой,
 * и никакой второй карты, расходящейся с первой, не появляется.
 *
 * Здесь только чистая Java — пакет core проверяется обычным JUnit
 * и не знает про Minecraft (см. {@code CorePurityTest}).
 */
public final class BorderMath {
    private BorderMath() {}

    /**
     * Ближайший к точке чанк уровня {@code минУровень} и выше.
     * Возвращает индекс ячейки сетки или {@code -1}, если такого нет.
     *
     * Радиус круглый, а не квадратный: волна прилива приходит «с той
     * стороны, где гниль», и в углу квадрата она приходила бы с полутора
     * радиусов — заметно дальше обещанного.
     *
     * При равном расстоянии выигрывает меньший индекс. Это не эстетика,
     * а воспроизводимость: одна и та же ночь в одном мире должна давать
     * один и тот же прилив, иначе проверять его на живом сервере нечем.
     */
    public static int ближайшийОчаг(PlagueGrid сетка, int чанкX, int чанкZ,
                                    int радиус, int минУровень) {
        int лучший = -1;
        int ближе = Integer.MAX_VALUE;
        int предел = радиус * радиус;

        for (int dz = -радиус; dz <= радиус; dz++) {
            for (int dx = -радиус; dx <= радиус; dx++) {
                int дистанция = dx * dx + dz * dz;
                if (дистанция > предел || дистанция >= ближе) continue;

                int cx = чанкX + dx;
                int cz = чанкZ + dz;
                if (!сетка.contains(cx, cz)) continue;
                if (сетка.getLevel(cx, cz) < минУровень) continue;

                ближе = дистанция;
                лучший = сетка.index(cx, cz);
            }
        }
        return лучший;
    }

    /**
     * Значение таблицы по уровню чанка.
     *
     * Индекс зажимается в границы намеренно: {@code getChunkLevel}
     * отдаёт −1 за краем мира, и без зажатия каждая примета за границей
     * сетки роняла бы сервер. −1 превращается в нулевой элемент, то есть
     * в «ничего не происходит», — ровно то поведение, которое нужно.
     */
    public static float поУровню(float[] таблица, int уровень) {
        return таблица[Math.clamp(уровень, 0, таблица.length - 1)];
    }

    /** То же для целых таблиц: состав волны по фазе, броски лута по уровню. */
    public static int поУровню(int[] таблица, int уровень) {
        return таблица[Math.clamp(уровень, 0, таблица.length - 1)];
    }
}
