package dev.denthe.plaguecore.core;

/**
 * Фазы финального боя по здоровью Сердца.
 *
 * Три фазы намеренно совпадают со слоями кусков модели: корни, ветки,
 * тело. Игрок видит фазу на самом Сердце, полоска здоровья для этого
 * не нужна.
 *
 * Считаем от доли, а не от абсолютных чисел: здоровье Сердца правится
 * в конфиге на живом сервере, и деление на три обязано ехать за ним.
 *
 * Дизайн — docs/superpowers/specs/2026-09-07-final-boj-design.md
 */
public final class FightPhases {
    private FightPhases() {}

    /** Сколько всего фаз. Задано слоями модели, в конфиг не выносится. */
    public static final int ФАЗ = 3;

    /**
     * Номер фазы боя, 1..3.
     *
     * Граница отдаётся следующей фазе: ровно две трети здоровья — это
     * уже вторая фаза. Так спазм срабатывает от удара, который границу
     * пересёк, а не от следующего за ним.
     *
     * @param здоровье текущее здоровье
     * @param максимум максимальное здоровье; 0 или меньше даёт первую фазу
     */
    public static int фаза(float здоровье, float максимум) {
        if (максимум <= 0f) return 1;
        float доля = здоровье / максимум;
        if (доля > 2f / 3f) return 1;
        if (доля > 1f / 3f) return 2;
        return ФАЗ;
    }
}
