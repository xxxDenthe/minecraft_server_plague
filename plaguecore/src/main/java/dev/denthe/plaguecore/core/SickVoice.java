package dev.denthe.plaguecore.core;

import dev.denthe.plaguecore.PlagueConstants;

import java.util.Random;

/**
 * Голос больного: чистая математика над кадром 20 мс, без единой ссылки
 * на Minecraft. Один экземпляр на говорящего — внутри живёт состояние
 * фильтров, поэтому кадры обязаны идти по порядку и в один поток.
 *
 * Первая версия была фильтром низких частот с ограничением и обрывами
 * кадров. Владелец послушал на живых людях: получилось не «человек болен»,
 * а «у человека сломан микрофон». Обрывы кадров и сильная глухота — это
 * ровно те приметы, по которым ухо опознаёт плохую связь, а не болезнь.
 * Поэтому обрывы убраны, глухота ослаблена, и добавлено то, чего не хватало:
 *
 *   1. Тон вниз. Отёкшие связки звучат ниже — это и есть главная примета.
 *   2. Дыхание. Шум не поверх формы волны, а по огибающей громкости:
 *      слышно, что человек выдыхает с трудом, а не что фонит провод.
 *   3. Хрип и дрожь — как были, но слабее: они приправа, а не блюдо.
 *
 * Числа живут в {@link PlagueConstants} и правятся конфигом или командой
 * `/plague voice` прямо на живом сервере: голос подбирается только слухом,
 * а слух требует крутить ручку и слушать, а не пересобирать мод.
 *
 * Тон сдвигаем линией задержки с двумя головками и перекрёстным
 * затуханием. Настоящий фазовый вокодер тут не нужен: на сдвиге в два-три
 * полутона линия даёт лёгкое «плавание» голоса, а для больного это
 * не изъян, а половина впечатления.
 */
public final class SickVoice {

    /** Частота дискретизации голосового чата: 48 кГц, кадр 20 мс = 960 сэмплов. */
    public static final float ЧАСТОТА = 48000f;

    /** Сколько уровней силы описано в константах. Уровень 0 — первая испорченная стадия. */
    public static final int УРОВНЕЙ = PlagueConstants.VOICE_LEVELS;

    /** Линия задержки: 2048 сэмплов ≈ 43 мс. Столько же и задержка голоса. */
    private static final int РАЗМЕР = 2048;
    /** Максимальная задержка. На два меньше буфера — под линейную интерполяцию. */
    private static final float ОКНО = РАЗМЕР - 2;

    /** Насколько быстро огибающая догоняет голос: ~20 мс на подъём. */
    private static final float СКОРОСТЬ_ОГИБАЮЩЕЙ = 0.001f;
    /** Фильтр самого шума: белый звучит цифровым шипением, приглушённый — дыханием. */
    private static final float МЯГКОСТЬ_ШУМА = 0.2f;

    private final Random случай;
    private final float[] линия = new float[РАЗМЕР];
    private int запись;
    private double фазаТона;
    private float память;        // фильтр низких частот
    private float огибающая;     // средняя громкость голоса
    private float шумПамять;     // фильтр шума дыхания
    private double фазаДрожи;

    public SickVoice() {
        this(new Random());
    }

    public SickVoice(Random случай) {
        this.случай = случай;
    }

    /**
     * Портит кадр на месте.
     *
     * @param звук кадр 16-битного моно, обычно 960 сэмплов
     * @param сила 0 для стадии 3, 1 для стадии 4; выходящее за края зажимается
     */
    public void обработать(short[] звук, int сила) {
        int с = Math.max(0, Math.min(сила, УРОВНЕЙ - 1));
        float скорость = (float) Math.pow(2.0, -PlagueConstants.VOICE_SEMITONES[с] / 12.0);
        float a = PlagueConstants.VOICE_MUFFLE[с];
        float k = PlagueConstants.VOICE_RASP[с];
        float шум = PlagueConstants.VOICE_BREATH[с];
        float глубина = PlagueConstants.VOICE_TREMOR[с];
        float нормировка = (float) Math.tanh(k);
        float шагДрожи = (float) (2 * Math.PI * PlagueConstants.VOICE_TREMOR_HZ / ЧАСТОТА);

        for (int i = 0; i < звук.length; i++) {
            float x = звук[i] / 32768f;

            огибающая += СКОРОСТЬ_ОГИБАЮЩЕЙ * (Math.abs(x) - огибающая);

            float y = сдвинуть(x, скорость);

            память += a * (y - память);
            y = память;

            y = (float) Math.tanh(k * y) / нормировка;

            if (шум > 0f) {
                шумПамять += МЯГКОСТЬ_ШУМА * ((случай.nextFloat() * 2f - 1f) - шумПамять);
                y += шумПамять * шум * огибающая * 3f;
            }

            if (глубина > 0f) {
                фазаДрожи += шагДрожи;
                y *= 1f - глубина * (0.5f + 0.5f * (float) Math.sin(фазаДрожи));
            }

            звук[i] = (short) Math.max(-32768, Math.min(32767, Math.round(y * 32768f)));
        }

        if (фазаДрожи > 2 * Math.PI) фазаДрожи %= 2 * Math.PI;
    }

    /**
     * Один сэмпл через линию задержки. Задержка растёт равномерно, значит
     * запись отматывается медленнее, чем пишется, — это и есть понижение
     * тона. Головок две, разнесённых на полокна, и когда одна доходит
     * до края буфера и прыгает назад, звук в этот миг ведёт вторая:
     * gains по синусу дают постоянную мощность, без провала на стыке.
     */
    private float сдвинуть(float x, float скорость) {
        линия[запись] = x;

        double ф2 = фазаТона + 0.5;
        if (ф2 >= 1) ф2 -= 1;

        float y = (float) (Math.sin(Math.PI * фазаТона) * взять((float) (фазаТона * ОКНО))
                         + Math.sin(Math.PI * ф2) * взять((float) (ф2 * ОКНО)));

        запись = (запись + 1) % РАЗМЕР;
        фазаТона += (1.0 - скорость) / ОКНО;
        if (фазаТона >= 1) фазаТона -= 1;
        return y;
    }

    /** Чтение из линии с дробной задержкой, линейная интерполяция. */
    private float взять(float задержка) {
        float поз = запись - задержка;
        if (поз < 0) поз += РАЗМЕР;
        int i = (int) поз;
        float дробь = поз - i;
        int j = i + 1;
        if (j >= РАЗМЕР) j = 0;
        return линия[i] * (1f - дробь) + линия[j] * дробь;
    }
}
