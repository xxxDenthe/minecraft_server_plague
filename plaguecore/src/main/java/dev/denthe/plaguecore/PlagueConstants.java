package dev.denthe.plaguecore;

/**
 * Все игровые числа в одном месте.
 *
 * Значения здесь — **стартовые**. Поверх них ложится конфиг
 * `config/plaguecore-common.toml`: при загрузке мира и при каждой правке
 * файла {@link PlagueConfig} перезаписывает поля ниже. Правило проекта —
 * за день до сессии баланс правится текстовым файлом, без пересборки,
 * поэтому поля нарочно не final.
 *
 * Разделение простое:
 *   нефинальное поле — ручка, её крутит человек из конфига;
 *   финальное поле   — устройство мода, менять на ходу нельзя.
 *
 * Класс остаётся чистой Java: конфиг знает о нём, а он о конфиге — нет.
 * Иначе пакет core потянул бы за собой NeoForge.
 */
public final class PlagueConstants {
    private PlagueConstants() {}

    // ── Устройство: на ходу не меняется ───────────────────────────────

    /** Максимальный уровень заражения чанка. 5 выставляет только подсистема логова. */
    public static final int MAX_LEVEL = 5;

    /** Потолок, до которого поднимается обычное распространение. */
    public static final int MAX_NATURAL_LEVEL = 4;

    /** Сторона мира в блоках. */
    public static final int WORLD_SIZE_BLOCKS = 1500;

    /**
     * Сторона сетки в чанках. 95 × 16 = 1520 — покрывает границу 1500
     * с запасом в 20 блоков. Число нечётное намеренно: у сетки должен
     * быть настоящий центральный чанк, вокруг которого /plague center
     * строит границу мира и точку возрождения.
     *
     * В конфиг не выносится намеренно: размер сетки записан в сохранение
     * мира, и смена числа на живом мире означала бы порчу данных.
     */
    public static final int GRID_SIZE_CHUNKS = 95;

    /**
     * Потолок очереди чанков на перерисовку.
     *
     * Тоже не ручка: очередь создаётся при загрузке класса, задолго
     * до того, как прочитан конфиг.
     */
    public static final int MAX_QUEUE_LENGTH = 512;

    // ── Ручки: их крутит конфиг ───────────────────────────────────────

    /** Сколько ночей держится шрам после полной очистки. */
    public static int SCAR_NIGHTS = 5;

    /** Во сколько раз растёт бюджет ночи, если игроки спали. */
    public static float SLEEP_BUDGET_MULTIPLIER = 2.0f;

    /** Дополнительный рост уровня на месте при сне. */
    public static int SLEEP_EXTRA_GROWTH = 1;

    /** Доля мира, заражённая на старте сессии. */
    public static float START_INFECTION_PERCENT = 0.10f;

    /**
     * Сколько очагов сажается на старте сессии.
     *
     * Число не косметическое, а определяющее темп: заражение растёт только
     * по краю очага, поэтому один большой очаг ползёт втрое медленнее, чем
     * та же площадь, разбитая на десятки мелких. При одном очаге к ночи 30
     * заражено 23% мира, при 32 — 75%, как и задумано спеком.
     * Разбор: docs/superpowers/notes/2026-09-03-krivaya-rasprostraneniya.md
     */
    public static int START_EPICENTERS = 32;

    // ── Ночные выводки у споровых мешков ──────────────────────────────

    /**
     * Вероятность, что за одну ночь у одного спорового мешка вылезет
     * кучка мобов. Внутри пересчитывается в шанс на случайный тик —
     * {@link dev.denthe.plaguecore.core.SpawnMath}.
     */
    public static float SPAWN_CHANCE_PER_NIGHT = 0.30f;

    /** Мутировавших зомби в одной кучке. */
    public static int SPAWN_ZOMBIES = 2;

    /** Скелетов в одной кучке. Скелеты ванильные: утром сгорают сами. */
    public static int SPAWN_SKELETONS = 2;

    /**
     * Сколько кучек за одну ночь может вылезти рядом с одним игроком.
     *
     * Главная защита от армии: в гнилом поле мешков бывает под сотню,
     * и без потолка каждый из них честно отсыпал бы свою четвёрку.
     */
    public static int SPAWN_MAX_GROUPS_PER_NIGHT = 3;

    /** Радиус вокруг мешка, в котором ищется место для мобов. */
    public static int SPAWN_RADIUS = 5;

    /** Ближе этого к игроку кучка не появляется: не лезем в лицо. */
    public static int SPAWN_MIN_PLAYER_DISTANCE = 12;

    // ── Материализация ────────────────────────────────────────────────
    // Дизайн материализации, раздел 8.

    /** Изменений блоков за тик на поверхности. Настоящая защита TPS. */
    public static int BLOCKS_PER_TICK = 128;

    /**
     * На сколько блоков вглубь от поверхности идёт материализация.
     *
     * Шесть, а не три. В ваниле дёрн лежит на трёх слоях земли, и камень
     * начинается ровно на четвёртом — то есть на первом же блоке за старой
     * границей. Из-за этого камень не заражался вообще никогда. Шесть даёт
     * три слоя камня под почвой, как просил владелец.
     */
    public static int SURFACE_DEPTH = 6;

    /** Доля обрастаемых наростом мест на поверхности: камень должен просвечивать. */
    public static float GROWTH_PATCH_FRACTION = 0.35f;

    /**
     * Доля столбцов, на которых вырастает споровый мешок.
     *
     * Заметно меньше пещерной: под землёй мешок — находка в тесноте,
     * а на открытой земле те же три процента дали бы восемь бугров
     * на чанк и превратили бы примету в сорняк.
     */
    public static float SURFACE_SPORE_SAC = 0.012f;

    // ── Подземелье ────────────────────────────────────────────────────
    // Ядро, раздел 8.4. Доли покрытия: какая часть подходящих мест
    // получает нарост. Пороги обязаны расти вместе с уровнем, иначе
    // покрытие перестанет быть вложенным и стены начнут выздоравливать;
    // за этим следит PlagueConfig при загрузке.

    /** Отдельный, более жёсткий лимит блоков за тик для подземелья. */
    public static int BLOCKS_PER_TICK_CAVE = 12;

    /** Стены пещер на уровнях 1–2: редкие пятна. */
    public static float CAVE_WALL_SPARSE = 0.15f;

    /** Стены пещер на Гнили: почти сплошь, но просветы остаются. */
    public static float CAVE_WALL_DENSE = 0.85f;

    /** Доля потолка, с которой свисают лозы. */
    public static float CAVE_CEILING_VINES = 0.20f;

    /** Доля пола, становящаяся гнилой землёй. */
    public static float CAVE_FLOOR_ROT = 0.45f;

    /** Доля пола под споровые мешки. Входит в долю гнилого пола. */
    public static float CAVE_SPORE_SAC = 0.03f;

    /**
     * Сколько столбцов чанка просматривается за тик под землёй.
     *
     * Отдельный потолок помимо бюджета блоков: столбец от дна мира
     * до поверхности — это сотня getBlockState, и пустой столбец
     * не тратит бюджет вовсе. Без этой границы чанк без пещер
     * прочёсывался бы целиком за один тик.
     */
    public static int CAVE_COLUMNS_PER_TICK = 16;

    // ── животные ──────────────────────────────────────────────────────

    /**
     * Раз во сколько тиков мирное животное проверяется на превращение.
     *
     * Проверка идёт в тике каждой сущности, поэтому интервал сторожит
     * не расчёт (одно чтение из сетки), а количество вызовов: сотня
     * коров на загруженных чанках иначе дёргала бы сетку каждый тик.
     */
    public static int ANIMAL_CHECK_TICKS = 100;

    /**
     * Шанс превращения за одну проверку на первом уровне заражения.
     * Умножается на уровень чанка, так что в Гнили животное портится
     * впятеро быстрее, чем на кромке.
     */
    public static float ANIMAL_INFECT_CHANCE = 0.04f;

    // ── игрок ─────────────────────────────────────────────────────────
    // Подсистема 2, спек 2026-09-04-zarazhenie-igroka-design.md.

    /** Раз во сколько тиков пересчитывается заражённость игрока. */
    public static int PLAYER_TICK_INTERVAL = 20;

    /**
     * Нижние границы стадий 1–4. Стадия 0 — всё, что ниже первой границы.
     * Обязаны идти по возрастанию; за этим следит PlagueConfig.
     */
    public static int[] PLAYER_STAGE_THRESHOLDS = { 10, 30, 60, 90 };

    /**
     * Сколько очков заражённости даёт секунда в чанке уровня N.
     * Индекс — уровень чанка 0–4. Нулевой отрицательный: чистый воздух лечит.
     */
    public static float[] PLAYER_EXPOSURE = { -0.05f, 0.01f, 0.04f, 0.10f, 0.20f };

    /** Во сколько раз быстрее копится зараза под землёй. */
    public static float PLAYER_UNDERGROUND_MULTIPLIER = 1.35f;

    /**
     * Временный штраф к максимуму здоровья по стадиям 0–4, в HP.
     * Снимается вместе с лечением.
     */
    public static float[] PLAYER_STAGE_HEALTH = { 0f, 0f, 2f, 6f, 6f };

    /** Во сколько раз слабее сытит еда начиная со стадии 1. */
    public static float PLAYER_FOOD_MULTIPLIER = 0.5f;

    /** Раз во сколько тиков стадия 4 бьёт игрока. 3600 тиков — три минуты. */
    public static int PLAYER_STAGE4_DAMAGE_TICKS = 3600;

    /** Сколько HP снимает удар стадии 4. */
    public static float PLAYER_STAGE4_DAMAGE = 2f;

    /** Раз во сколько тиков кашляет игрок каждой стадии 0–4. Ноль — не кашляет. */
    public static int[] PLAYER_COUGH_TICKS = { 0, 600, 300, 200, 200 };

    /** Шанс заразить соседа одним кашлем, по стадии кашляющего 0–4. */
    public static float[] PLAYER_COUGH_CHANCE = { 0f, 0f, 0.35f, 0.50f, 0.50f };

    /** Радиус кашля в блоках. Шесть, а не два: больного нельзя вести с собой. */
    public static float PLAYER_COUGH_RADIUS = 6f;

    /** Сколько очков получает сосед, которому не повезло. */
    public static float PLAYER_COUGH_AMOUNT = 4f;

    /** Сколько очков снимает N-й глоток отвара подряд. Последнее — для всех дальнейших. */
    public static float[] PLAYER_BREW_STRENGTH = { 13f, 10f, 8f, 7f, 6f, 5f };

    /** Через сколько тиков без глотка счётчик отваров обнуляется. 6000 — пять минут. */
    public static int PLAYER_BREW_RESET_TICKS = 6000;

    /** Выше этой стадии отвар не действует. Стадии 3 и 4 — только Клирик. */
    public static int PLAYER_BREW_MAX_STAGE = 2;

    /** Сколько HP навсегда снимает смерть на стадии 2+. */
    public static float PLAYER_DEATH_PENALTY = 1f;

    /** Пол постоянных потерь: ниже этого максимум здоровья не опускают смерти. */
    public static float PLAYER_PERMANENT_FLOOR = 6f;

    /**
     * Жёсткий пол итогового максимума. Постоянные потери и временный штраф
     * стадии складываются; без этого предела они складываются в ноль,
     * и игрок умирает бесконечно при возрождении.
     */
    public static float PLAYER_HARD_FLOOR = 4f;

    // ── голос больного ────────────────────────────────────────────────
    // Разбор эффекта — docs/superpowers/notes/2026-09-05-golos-i-kashel.md.
    // Все массивы длины VOICE_LEVELS: [0] — первая испорченная стадия,
    // [1] — все следующие. Правятся вживую через /plague voice.

    /** Сколько уровней силы описано в массивах ниже. */
    public static final int VOICE_LEVELS = 2;

    /** Ниже этой стадии голос не трогаем вовсе. */
    public static int VOICE_MIN_STAGE = 3;

    /** На сколько полутонов опустить голос. */
    public static float[] VOICE_SEMITONES = { 1.5f, 3.2f };

    /** Сила фильтра низких частот, 0..1: меньше — глуше. */
    public static float[] VOICE_MUFFLE = { 0.45f, 0.30f };

    /** Жёсткость мягкого ограничения: больше — сильнее хрип. */
    public static float[] VOICE_RASP = { 1.5f, 2.6f };

    /** Громкость дыхания как доля от огибающей голоса. */
    public static float[] VOICE_BREATH = { 0.15f, 0.45f };

    /** Глубина дрожи, 0..1. */
    public static float[] VOICE_TREMOR = { 0.10f, 0.26f };

    /** Частота дрожи в герцах. */
    public static float VOICE_TREMOR_HZ = 5.5f;

    // ── Сердце чумы ───────────────────────────────────────────────────

    /**
     * Здоровье Сердца. Двадцать кусков модели делят его поровну:
     * при 200 HP каждый кусок стоит 10 урона.
     *
     * Читается в конструкторе сущности, поэтому правка конфига на живом
     * сервере доходит до уже поставленных Сердец только после перезахода
     * в мир. Для настройки это не мешает: Сердце ставят заново одной командой.
     */
    public static float HEART_HEALTH = 200f;

    /**
     * Во сколько раз Сердце крупнее исходной модели. Растёт и картинка,
     * и хитбокс: бить по пустому месту или мимо видимого куска нельзя.
     *
     * Хитбокс, как и здоровье, читается при появлении сущности, так что
     * уже стоящее Сердце подхватит новый размер после перезахода в мир.
     */
    public static float HEART_SCALE = 1.5f;
}
