package dev.denthe.classes;

import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Направление вместо уровня — то, что Летописец видит взамен
 * отобранных у него точных чисел. Спек классов, раздел 7.
 */
class TrendTest {

    @Test
    void мёртваяЗонаГаситШум() {
        assertEquals(Trend.БЕЗ_ПЕРЕМЕН, Trend.знак(10f, 10.4f, 0.5f));
        assertEquals(Trend.БЕЗ_ПЕРЕМЕН, Trend.знак(10f, 9.6f, 0.5f));
        assertEquals(Trend.ХУЖЕ, Trend.знак(10f, 10.6f, 0.5f));
        assertEquals(Trend.ЛЕГЧЕ, Trend.знак(10f, 9.4f, 0.5f));
    }

    @Test
    void одногоЗамераМалоДляСуждения() {
        Trend.Кольцо кольцо = new Trend.Кольцо();
        assertEquals(Trend.НЕИЗВЕСТНО, кольцо.знак(0.5f), "пустому кольцу сказать нечего");
        кольцо.добавить(12f);
        assertEquals(Trend.НЕИЗВЕСТНО, кольцо.знак(0.5f), "сравнивать не с чем");
        кольцо.добавить(20f);
        assertEquals(Trend.ХУЖЕ, кольцо.знак(0.5f));
    }

    @Test
    void кольцоЗабываетТоЧтоВышлоИзОкна() {
        Trend.Кольцо кольцо = new Trend.Кольцо();
        кольцо.добавить(100f);                       // давний всплеск
        for (int i = 0; i < Trend.ЗАМЕРОВ; i++) {
            кольцо.добавить(10f);                    // вытесняет его целиком
        }
        assertEquals(Trend.ЗАМЕРОВ, кольцо.сколько());
        assertEquals(10f, кольцо.старейший(), 0.001f);
        assertEquals(Trend.БЕЗ_ПЕРЕМЕН, кольцо.знак(0.5f),
            "вышедший из окна всплеск не должен держать стрелку вечно");
    }

    @Test
    void свежийИСтарейшийНеПутаются() {
        Trend.Кольцо кольцо = new Trend.Кольцо();
        кольцо.добавить(1f);
        кольцо.добавить(2f);
        кольцо.добавить(3f);
        assertEquals(1f, кольцо.старейший(), 0.001f);
        assertEquals(3f, кольцо.свежий(), 0.001f);
        assertEquals(Trend.ХУЖЕ, кольцо.знак(0.5f));
    }

    @Test
    void лечениеВидноКакОблегчение() {
        Trend.Кольцо кольцо = new Trend.Кольцо();
        кольцо.добавить(40f);
        кольцо.добавить(38f);
        кольцо.добавить(12f);                        // выпил отвар
        assertEquals(Trend.ЛЕГЧЕ, кольцо.знак(0.5f));
    }

    @Test
    void окноРовноДвеМинуты() {
        assertEquals(2400, Trend.ЗАМЕРОВ * Trend.ТИКОВ_МЕЖДУ_ЗАМЕРАМИ,
            "восемь замеров по пятнадцать секунд — две минуты, как решено с владельцем");
    }
}
