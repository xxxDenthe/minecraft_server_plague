package dev.denthe.classes;

import net.minecraft.server.MinecraftServer;
import net.minecraft.server.level.ServerPlayer;

/**
 * Мастерство партии, а не отдельного игрока. Спек классов, раздел 2.1.
 *
 * Постройки читают не того, кто их поставил, а лучшего специалиста
 * среди тех, кто **сейчас в игре**. Из этого следует главное свойство,
 * ради которого правило и заведено: ушёл единственный Кузнец в другой
 * класс или вышел из игры — оборона проседает до уровня, доступного
 * без класса, и восстанавливается сама, когда Кузнец вернётся.
 * Личной привязки блока к игроку нет намеренно: коллективная защита
 * сильна ровно настолько, насколько партия вложилась в класс прямо
 * сейчас.
 */
public final class ClassParty {
    private ClassParty() {}

    /** Игрок этого класса с наибольшим мастерством; {@code null}, если таких нет в игре. */
    public static ServerPlayer лучший(MinecraftServer сервер, PlayerClassData.Класс класс) {
        ServerPlayer лучший = null;
        int максимум = -1;
        for (ServerPlayer игрок : сервер.getPlayerList().getPlayers()) {
            PlayerClassData д = PlayerClassData.данные(игрок);
            if (д.класс != класс) continue;
            if (д.мастерство > максимум) {
                максимум = д.мастерство;
                лучший = игрок;
            }
        }
        return лучший;
    }

    /**
     * Тир, который партия тянет по этому классу: 1..3, либо {@code 0},
     * если ни одного такого специалиста сейчас нет. Ноль — это и есть
     * «уровень, доступный без класса» из спека.
     */
    public static int тир(MinecraftServer сервер, PlayerClassData.Класс класс) {
        ServerPlayer лучший = лучший(сервер, класс);
        return лучший == null ? 0 : PlayerClassData.данные(лучший).тир();
    }
}
