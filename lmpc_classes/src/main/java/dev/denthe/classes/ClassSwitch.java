package dev.denthe.classes;

/**
 * Кулдаун смены класса. Спек — 2026-09-04-klassy-design.md, раздел 2,
 * в основном репозитории (`plaguecore` соседним модом не трогаем).
 *
 * Класс не выбирается один раз намертво — алтарь меняет его в игре,
 * но не чаще, чем раз в {@code classSwitchCooldownMinutes}. Иначе
 * переобуваться под каждую ситуацию можно было бы посреди одного боя.
 *
 * Без импортов Minecraft нарочно: чистые функции, проверяются обычным
 * JUnit без запуска игры ({@code ClassSwitchTest}).
 */
public final class ClassSwitch {
    private ClassSwitch() {}

    /** Тиков в игровой минуте: 20 в секунде. */
    public static final long ТИКОВ_В_МИНУТЕ = 1200L;

    /**
     * @param последняяСменаТик мировой тик прошлой смены, −1 — ни разу не менял
     * @param текущийТик        мировой тик сейчас
     * @param кулдаунТики       минимальный интервал между сменами
     */
    public static boolean можноСменить(long последняяСменаТик, long текущийТик, long кулдаунТики) {
        if (последняяСменаТик < 0) return true;
        return текущийТик - последняяСменаТик >= кулдаунТики;
    }

    /** Сколько тиков ещё ждать; 0 — можно менять прямо сейчас. */
    public static long осталосьТиков(long последняяСменаТик, long текущийТик, long кулдаунТики) {
        if (можноСменить(последняяСменаТик, текущийТик, кулдаунТики)) return 0L;
        return кулдаунТики - (текущийТик - последняяСменаТик);
    }

    /**
     * Тики в минуты для показа игроку, с округлением вверх: «через
     * 0 минут» на живом кулдауне читается как ошибка, а «через 1» —
     * как правда. Ровно ноль остаётся нулём.
     */
    public static long минутОсталось(long тиков) {
        if (тиков <= 0) return 0L;
        return (тиков - 1) / ТИКОВ_В_МИНУТЕ + 1;
    }
}
