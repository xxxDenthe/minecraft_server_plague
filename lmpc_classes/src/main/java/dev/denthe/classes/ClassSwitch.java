package dev.denthe.classes;

/**
 * Кулдаун смены класса. Спек — 2026-09-04-klassy-design.md, раздел 2,
 * в основном репозитории (`plaguecore` соседним модом не трогаем).
 *
 * Класс не выбирается один раз намертво — путёвка меняет его в игре,
 * но не чаще, чем раз в {@code classSwitchCooldownMinutes}. Иначе
 * переобуваться под каждую ситуацию можно было бы посреди одного боя.
 *
 * Без импортов Minecraft нарочно: чистая функция, проверяется обычным
 * JUnit без запуска игры.
 */
public final class ClassSwitch {
    private ClassSwitch() {}

    /**
     * @param последняяСменаТик мировой тик прошлой смены, −1 — ни разу не менял
     * @param текущийТик        мировой тик сейчас
     * @param кулдаунТики       минимальный интервал между сменами
     */
    public static boolean можноСменить(long последняяСменаТик, long текущийТик, long кулдаунТики) {
        if (последняяСменаТик < 0) return true;
        return текущийТик - последняяСменаТик >= кулдаунТики;
    }
}
