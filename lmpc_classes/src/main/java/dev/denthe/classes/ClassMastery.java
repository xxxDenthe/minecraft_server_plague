package dev.denthe.classes;

/**
 * Мастерство и его тиры. Спек — 2026-09-04-klassy-design.md, разделы
 * 2.1 и 11: «мастерство делится на тиры той же формы, что была
 * у Очистителя Кузнеца (1/2/3) — общая идея для всех классов».
 *
 * Тир — не отдельное поле, а функция от накопленного числа: хранить
 * его в данных игрока значило бы держать две правды об одном и том же.
 *
 * Без импортов Minecraft нарочно, как {@link ClassSwitch}: чистые
 * функции, проверяются обычным JUnit без запуска игры
 * ({@code ClassMasteryTest}).
 */
public final class ClassMastery {
    private ClassMastery() {}

    /** Потолок мастерства. Полоса в гримуаре рисуется как доля от него. */
    public static final int МАКСИМУМ = 100;

    /** Прибавить с зажимом в 0..{@link #МАКСИМУМ}. Отрицательное — вычитает. */
    public static int прибавить(int мастерство, int сколько) {
        return Math.max(0, Math.min(МАКСИМУМ, мастерство + сколько));
    }

    /**
     * Тир 1/2/3. Пороги приходят из конфига, поэтому их порядок
     * не гарантирован — переставленные местами числа не должны
     * выдавать третий тир на пустом мастерстве.
     */
    public static int тир(int мастерство, int порог2, int порог3) {
        int нижний = Math.min(порог2, порог3);
        int верхний = Math.max(порог2, порог3);
        if (мастерство >= верхний) return 3;
        if (мастерство >= нижний) return 2;
        return 1;
    }

    /** Порог следующего тира; −1, если тир уже третий. */
    public static int следующийПорог(int мастерство, int порог2, int порог3) {
        int нижний = Math.min(порог2, порог3);
        int верхний = Math.max(порог2, порог3);
        if (мастерство < нижний) return нижний;
        if (мастерство < верхний) return верхний;
        return -1;
    }

    /**
     * Множитель силы пассивки по тиру: первый тир — как в конфиге,
     * каждый следующий добавляет {@code шагЗаТир}. Один множитель на
     * все четыре класса — тир должен значить одно и то же, чем бы
     * ты ни играл.
     */
    public static float множительСилы(int тир, double шагЗаТир) {
        return (float) (1.0 + Math.max(0, тир - 1) * Math.max(0.0, шагЗаТир));
    }

    /**
     * Множитель кулдауна по тиру: чем выше тир, тем короче ожидание,
     * но не короче десятой доли — иначе третий тир снимает кулдаун
     * целиком и активка перестаёт быть решением.
     */
    public static float множительКулдауна(int тир, double шагЗаТир) {
        return (float) Math.max(0.1, 1.0 - Math.max(0, тир - 1) * Math.max(0.0, шагЗаТир));
    }

    private static final String[] РИМСКИЕ = { "I", "II", "III", "IV" };

    /**
     * Римская цифра тира 1..4; вне диапазона — само число.
     * Живёт здесь, а не в клиентской палитре: тир печатают и серверные
     * сообщения (состояние очистителя, админские команды), а клиентский
     * пакет на сервере не загрузится.
     */
    public static String римская(int номер) {
        return номер >= 1 && номер <= РИМСКИЕ.length ? РИМСКИЕ[номер - 1] : Integer.toString(номер);
    }
}
