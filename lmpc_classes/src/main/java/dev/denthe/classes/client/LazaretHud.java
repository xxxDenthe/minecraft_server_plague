package dev.denthe.classes.client;

import net.minecraft.client.gui.GuiGraphics;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.ResourceLocation;

/**
 * Окошки Летописца в шкуре полевого лазарета.
 *
 * Обе панели Летописца — летопись и снимок — раньше рисовались плоской
 * заливкой с цветной каймой и выглядели чужими рядом с экраном осмотра
 * (клавиша `Y`), сделанным как просмолённый кожаный планшет. Владелец
 * попросил свести их к одному виду, не перенося внутрь экрана: панельки
 * остаются поверх игры, но одеваются в ту же кожу и латунь.
 *
 * <p><b>Рамка — свой лист, шрифт — чужой.</b> Заготовка
 * {@code lazaret_frame.png} лежит в этом моде, хотя место в листе
 * планшета было: `health_panel.png` живёт в `plaguecore`, а два мода
 * правятся из разных сессий, и разошедшийся PNG не слить руками.
 * Шрифт заголовков остаётся общим — это ссылка, а не правка чужого
 * файла, и панели Летописца всё равно пусты без `plaguecore` (числа
 * заражения считает он). Обе картинки рисует
 * {@code tools/lazaret-gfx/графика.py} — числа ниже обязаны совпадать
 * с числами там.
 *
 * <p>Края и середина <b>размножаются плиткой, а не растягиваются</b>:
 * растянутая кожа расчёсывается в полосы, и от пиксельной графики
 * проекта ничего не остаётся.
 */
public final class LazaretHud {
    private LazaretHud() {}

    private static final ResourceLocation ЛИСТ =
        ResourceLocation.fromNamespaceAndPath(
            dev.denthe.classes.LmpcClasses.MODID, "textures/gui/lazaret_frame.png");

    /** Шрифт заголовков планшета: узкая прописная антиква в семь пикселей. */
    private static final ResourceLocation КЛЕЙМО =
        ResourceLocation.fromNamespaceAndPath("plaguecore", "lazaret");

    /** Лист — ровно заготовка окна: квадрат со стороной 48. */
    private static final int ЛИСТ_С = 48;

    /** Сторона угла заготовки. Середина и края — такие же квадраты. */
    private static final int УГОЛ = 16;

    /** Тёплая костяная гамма планшета: серый на кожаном фоне мертвеет. */
    public static final int ТЕКСТ = 0xFFE2DDCE;
    public static final int ТУСКЛЫЙ = 0xFF9B9280;
    public static final int КОСТЬ = 0xFFD9CCA6;
    public static final int ЛАТУНЬ = 0xFF8A7241;

    /** Заголовок окошка — тем же клеймёным шрифтом, что и заголовок планшета. */
    public static Component клеймо(String ключ) {
        return Component.translatable(ключ).withStyle(с -> с.withFont(КЛЕЙМО));
    }

    /** Отступ от края панельки до содержимого. Внутри рамки и заклёпок. */
    public static final int ПОЛЕ = 7;

    /**
     * Нарисовать кожаное окошко. Размеры меньше двух углов не бывают —
     * при таких рамка всё равно не соберётся, поэтому прижимаем.
     */
    public static void панель(GuiGraphics графика, int x, int y, int ш, int в) {
        ш = Math.max(ш, УГОЛ * 2);
        в = Math.max(в, УГОЛ * 2);

        int правый = x + ш - УГОЛ, нижний = y + в - УГОЛ;
        int середина = ЛИСТ_С - УГОЛ * 2;        // край заготовки под плитку

        кусок(графика, x, y, УГОЛ, УГОЛ, 0, 0);
        кусок(графика, правый, y, УГОЛ, УГОЛ, УГОЛ + середина, 0);
        кусок(графика, x, нижний, УГОЛ, УГОЛ, 0, УГОЛ + середина);
        кусок(графика, правый, нижний, УГОЛ, УГОЛ, УГОЛ + середина, УГОЛ + середина);

        for (int сдвиг = 0; сдвиг < ш - УГОЛ * 2; сдвиг += середина) {
            int шаг = Math.min(середина, ш - УГОЛ * 2 - сдвиг);
            кусок(графика, x + УГОЛ + сдвиг, y, шаг, УГОЛ, УГОЛ, 0);
            кусок(графика, x + УГОЛ + сдвиг, нижний, шаг, УГОЛ, УГОЛ, УГОЛ + середина);
        }
        for (int сдвиг = 0; сдвиг < в - УГОЛ * 2; сдвиг += середина) {
            int шаг = Math.min(середина, в - УГОЛ * 2 - сдвиг);
            кусок(графика, x, y + УГОЛ + сдвиг, УГОЛ, шаг, 0, УГОЛ);
            кусок(графика, правый, y + УГОЛ + сдвиг, УГОЛ, шаг, УГОЛ + середина, УГОЛ);
        }
        for (int по = 0; по < в - УГОЛ * 2; по += середина) {
            int высота = Math.min(середина, в - УГОЛ * 2 - по);
            for (int вдоль = 0; вдоль < ш - УГОЛ * 2; вдоль += середина) {
                int ширина = Math.min(середина, ш - УГОЛ * 2 - вдоль);
                кусок(графика, x + УГОЛ + вдоль, y + УГОЛ + по, ширина, высота, УГОЛ, УГОЛ);
            }
        }
    }

    /** Один кусок заготовки один к одному, без растяжения. */
    private static void кусок(GuiGraphics графика, int x, int y, int ш, int в, int u, int v) {
        графика.blit(ЛИСТ, x, y, ш, в, u, v, ш, в, ЛИСТ_С, ЛИСТ_С);
    }
}
