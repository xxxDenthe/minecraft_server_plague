package dev.denthe.classes;

/**
 * Упаковка сетки снимка Летописца — договор между отправителем
 * ({@link ChroniclerSnapshot}) и экраном ({@code client.SnapshotHud}).
 *
 * Вынесено в отдельный класс по одной причине: обе стороны обязаны
 * читать одну и ту же сетку одинаково, а расходятся такие вещи молча.
 * Ошибка знака в байте («уровень 255» вместо «нет данных») не уронит
 * ничего — просто нарисует чужую карту, и найдётся это только глазами
 * в игре.
 *
 * Без импортов Minecraft — проверяется обычным JUnit, тем же правилом,
 * что {@link ClassMastery} и {@link ClassSwitch}.
 */
public final class SnapshotGrid {
    private SnapshotGrid() {}

    /** Так помечается чанк вне сетки мира: в байте это 0xFF, в int — 255. */
    public static final int НЕТ_ДАННЫХ = 255;

    /**
     * Сторона квадрата в чанках по радиусу, с потолком на размер пакета.
     * Всегда нечётная: у снимка есть центр — чанк, где стоял Летописец.
     * Радиус 0 — это ровно свой чанк, а не «принудительно три на три».
     */
    public static int сторона(int радиус, int максимум) {
        return Math.min(Math.max(0, радиус) * 2 + 1, максимум);
    }

    /** Уровень 0..5 в байт; отрицательный (чанк вне мира) — в {@link #НЕТ_ДАННЫХ}. */
    public static byte упаковать(int уровень) {
        return (byte) (уровень < 0 ? НЕТ_ДАННЫХ : уровень);
    }

    /**
     * Байт обратно в уровень. Именно здесь живёт снятие знака: байт
     * в Java знаковый, и 0xFF без маски читается как −1, а не как
     * «нет данных».
     */
    public static int распаковать(byte значение) {
        return значение & 0xFF;
    }

    /** Номер клетки в плоском массиве. Сетка построчная, с севера на юг. */
    public static int индекс(int dx, int dz, int сторона) {
        return dz * сторона + dx;
    }
}
