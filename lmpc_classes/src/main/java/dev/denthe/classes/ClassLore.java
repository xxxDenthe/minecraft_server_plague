package dev.denthe.classes;

/**
 * Тексты гримуара: заголовок, роль одной строкой, лор-абзац.
 * Спек, раздел 4–7 — роли взяты оттуда буквально, лор-абзацы —
 * черновик для заполнения экрана, не финальный текст: лор — не
 * моя территория, писать/править владельцу.
 */
final class ClassLore {
    private ClassLore() {}

    record Запись(String заголовок, String роль, String лор) {}

    static Запись записьДля(PlayerClassData.Класс класс) {
        return switch (класс) {
            case CLERIC -> new Запись(
                "Клирик",
                "Лекарь партии на поздних стадиях чумы",
                "Отвар и молитва бессильны там, где чума берёт своё — "
                    + "но Клирик остаётся рядом, когда остальные лекарства "
                    + "уже не действуют. Твёрдая рука и голос у самого уха "
                    + "иногда решают больше, чем любой рецепт.");
            case SMITH -> new Запись(
                "Кузнец",
                "Техник обороны, держит Очистители поверхности",
                "Пока другие бегут от Гнили, Кузнец строит то, что держит "
                    + "её на расстоянии. Машина не устаёт и не боится — "
                    + "но она голодна, и без хозяина ржавеет так же, как "
                    + "любой брошенный механизм.");
            case FARMER -> new Запись(
                "Фермер",
                "Превращает поход за сырьём чумы в хозяйство",
                "То, что растёт диким кустом в Гнили — риск для тех, кто "
                    + "идёт за ним с пустыми руками. Фермер приручил его: "
                    + "то же самое всходит рядами на его грядке, безопасно "
                    + "и предсказуемо, как любой урожай.");
            case CHRONICLER -> new Запись(
                "Летописец",
                "Разведчик и глаза партии",
                "Летописец идёт туда, куда остальные не хотят смотреть, "
                    + "и записывает, что видел — на случай, если сам "
                    + "не вернётся. Каждый снимок и каждая строка когда-нибудь "
                    + "станут единственным свидетельством того, что здесь было.");
            case NONE -> new Запись("Без класса", "", "");
        };
    }
}
