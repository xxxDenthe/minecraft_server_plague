package dev.denthe.classes;

/**
 * Куда катится здоровье человека — знак перемены за окно наблюдения.
 * Спек классов, раздел 7.
 *
 * Летописец больше не видит ни стадии, ни заражённости: точные числа
 * делали его всеведущим и отбирали работу у Клирика. Вместо уровня он
 * видит направление — «хуже», «легче», «без перемен». Клирик говорит,
 * <i>насколько</i> плохо сейчас; Летописец — <i>куда</i> идёт дело,
 * и эти два знания не заменяют друг друга.
 *
 * <p>Класс ничего не знает ни о Minecraft, ни о сети: кольцо значений
 * и знак разницы — обычная арифметика, и проверяется она обычным JUnit.
 * Наружу из мода уходит только знак, поэтому подменённый клиент не
 * вычитает из пакета исходные очки заражённости — их там просто нет.
 */
public final class Trend {
    private Trend() {}

    /** Значения знака. Совпадают с тем, что уходит в пакет. */
    public static final int НЕИЗВЕСТНО = -2, ЛЕГЧЕ = -1, БЕЗ_ПЕРЕМЕН = 0, ХУЖЕ = 1;

    /**
     * Сколько замеров держим на человека. Замер раз в
     * {@link #ТИКОВ_МЕЖДУ_ЗАМЕРАМИ} — восемь штук дают окно в две минуты,
     * то самое, за которое успевает сказаться и туман, и отвар.
     */
    public static final int ЗАМЕРОВ = 8;

    /** Раз во сколько тиков снимается замер. 300 = пятнадцать секунд. */
    public static final int ТИКОВ_МЕЖДУ_ЗАМЕРАМИ = 300;

    /**
     * Кольцо замеров одного человека: свежий вытесняет самый старый.
     * Восемь чисел на игрока — дешевле, чем любая история с временем,
     * а больше для знака и не нужно.
     */
    public static final class Кольцо {
        private final float[] замеры = new float[ЗАМЕРОВ];
        private int сколько;
        private int следующий;

        public void добавить(float значение) {
            замеры[следующий] = значение;
            следующий = (следующий + 1) % ЗАМЕРОВ;
            if (сколько < ЗАМЕРОВ) сколько++;
        }

        public int сколько() {
            return сколько;
        }

        /** Самый старый замер в окне. Бросать нечего: спрашивают после проверки. */
        public float старейший() {
            int индекс = сколько < ЗАМЕРОВ ? 0 : следующий;
            return замеры[индекс];
        }

        /** Самый свежий замер. */
        public float свежий() {
            return замеры[(следующий + ЗАМЕРОВ - 1) % ЗАМЕРОВ];
        }

        /**
         * Знак перемены за окно. Пока замеров меньше двух, честный
         * ответ — «неизвестно»: человек только что попал в поле зрения,
         * и сравнивать не с чем.
         */
        public int знак(float порог) {
            if (сколько < 2) return НЕИЗВЕСТНО;
            return Trend.знак(старейший(), свежий(), порог);
        }
    }

    /**
     * Знак разницы с мёртвой зоной. Без порога панель дёргалась бы
     * каждую секунду от дробных долей очка — читать такое нельзя.
     */
    public static int знак(float старое, float новое, float порог) {
        float разница = новое - старое;
        if (Math.abs(разница) < порог) return БЕЗ_ПЕРЕМЕН;
        return разница > 0 ? ХУЖЕ : ЛЕГЧЕ;
    }
}
