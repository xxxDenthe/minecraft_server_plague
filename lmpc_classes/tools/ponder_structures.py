"""Генератор структур для сцен «размышления» (Ponder) очистителей.

Ponder показывает не выдуманную сцену, а настоящую постройку из файла
`assets/lmpc_classes/ponder/<имя>.nbt` — это ванильный формат структурного
блока, тот же, что у /structure save. Своего редактора у нас нет, а
руками такой файл не написать: он двоичный и упакован gzip.

Поэтому постройка описана здесь кодом, а файл пересобирается командой

    python tools/ponder_structures.py

Класть в репозиторий и сам скрипт, и .nbt: файл — ресурс мода, а скрипт —
единственный способ его потом поправить.
"""

import gzip
import os
import struct

DATA_VERSION = 3955  # Minecraft 1.21.1

# --- минимальный писатель NBT: только те теги, что нужны структуре ---

def _имя(строка):
    b = строка.encode("utf-8")
    return struct.pack(">H", len(b)) + b

def именованный(тип, имя, тело):
    return bytes([тип]) + _имя(имя) + тело

def целое(значение):
    return struct.pack(">i", значение)

def строка(значение):
    return _имя(значение)

def список(тип_элемента, элементы):
    return bytes([тип_элемента]) + struct.pack(">i", len(элементы)) + b"".join(элементы)

def составной(пары):
    """пары: [(тип, имя, тело), ...]"""
    return b"".join(именованный(т, н, п) for т, н, п in пары) + b"\x00"

СОСТАВНОЙ, СПИСОК, ЦЕЛОЕ, СТРОКА = 10, 9, 3, 8


def блок(имя, свойства=None):
    return (имя, tuple(sorted((свойства or {}).items())))


def структура(размер, блоки):
    """размер: (x, y, z); блоки: {(x, y, z): (имя, свойства)}"""
    палитра = []
    индекс = {}
    for ключ in блоки.values():
        if ключ not in индекс:
            индекс[ключ] = len(палитра)
            палитра.append(ключ)

    палитра_нбт = []
    for имя, свойства in палитра:
        пары = [(СТРОКА, "Name", строка(имя))]
        if свойства:
            пары.append((СОСТАВНОЙ, "Properties", составной(
                [(СТРОКА, к, строка(з)) for к, з in свойства])))
        палитра_нбт.append(составной(пары))

    блоки_нбт = [
        составной([
            (СПИСОК, "pos", список(ЦЕЛОЕ, [целое(к) for к in позиция])),
            (ЦЕЛОЕ, "state", целое(индекс[ключ])),
        ])
        for позиция, ключ in sorted(блоки.items())
    ]

    return составной([
        (ЦЕЛОЕ, "DataVersion", целое(DATA_VERSION)),
        (СПИСОК, "size", список(ЦЕЛОЕ, [целое(к) for к in размер])),
        (СПИСОК, "palette", список(СОСТАВНОЙ, палитра_нбт)),
        (СПИСОК, "blocks", список(СОСТАВНОЙ, блоки_нбт)),
        (СПИСОК, "entities", список(СОСТАВНОЙ, [])),
    ])


def сцена(очиститель):
    """Площадка 5 × 5, привод слева, очиститель в середине.

    Ряд «мотор — вал — очиститель» стоит по оси X специально: сцена
    показывает главное правило блока — вращение должно приходить
    от соседа, а не «откуда-нибудь рядом».
    """
    блоки = {}
    for x in range(5):
        for z in range(5):
            блоки[(x, 0, z)] = блок("minecraft:polished_andesite")
    блоки[(0, 1, 2)] = блок("create:creative_motor", {"facing": "east"})
    блоки[(1, 1, 2)] = блок("create:shaft", {"axis": "x", "waterlogged": "false"})
    блоки[(2, 1, 2)] = блок(очиститель, {"lit": "false"})
    return структура((5, 2, 5), блоки)


if __name__ == "__main__":
    куда = os.path.normpath(os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..",
        "src", "main", "resources", "assets", "lmpc_classes", "ponder"))
    os.makedirs(куда, exist_ok=True)
    for имя, блок_очистителя in (
        ("andesite_purifier", "lmpc_classes:andesite_purifier"),
        ("brass_purifier", "lmpc_classes:brass_purifier"),
    ):
        путь = os.path.join(куда, имя + ".nbt")
        with gzip.open(путь, "wb") as ф:
            ф.write(именованный(СОСТАВНОЙ, "", сцена(блок_очистителя)))
        print(имя, os.path.getsize(путь), "bytes")
