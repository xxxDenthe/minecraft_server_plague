# -*- coding: utf-8 -*-
"""
Текстуры кнопки «Войти в деревню» для стартового экрана.

FancyMenu умеет у кнопки ровно две картинки — обычную и под курсором
(`backgroundnormal` и `backgroundhovered`), и вторая может быть
анимированной: APNG и GIF мод читает сам. Свойства «подсветить»,
«залить градиентом» или «пустить блик» у него нет, поэтому весь эффект
наведения рисуется здесь заранее, кадр за кадром.

Взято APNG, а не GIF: в GIF всего 256 цветов на кадр, а тут сплошные
мягкие переходы латуни по тёмному — их бы разбило полосами.

Запускается сам из `make-welcome-screen.py`; отдельно — если нужно
посмотреть только картинки:

    python launcher/tools/make-welcome-button.py

Размеры берутся из генератора экрана, чтобы текстура и кнопка не
разъезжались: `make-welcome-screen.py` — единственное место, где
правится раскладка.
"""

import math
from pathlib import Path

import numpy as np
from PIL import Image

КОРЕНЬ = Path(__file__).resolve().parents[1]
ПАПКА = КОРЕНЬ / "pack-config" / "config" / "fancymenu" / "assets"
ОБЫЧНАЯ = ПАПКА / "lmpc_button.png"
НАВЕДЁННАЯ = ПАПКА / "lmpc_button_hover.apng"

# Точка раскладки при масштабе интерфейса 2 — это два пикселя экрана.
# Рисуем сразу в пикселях, чтобы кнопка не размывалась растяжением.
ПИКСЕЛЕЙ_В_ТОЧКЕ = 2

КАДРОВ = 32
МС_НА_КАДР = 45          # цикл ~1.4 с: заметно, но не суетливо

ФОН = (0x19, 0x16, 0x12)     # плашка, чуть светлее нижней полосы экрана
ЛАТУНЬ = (0xC2, 0xA8, 0x7C)  # тот же акцент, что у названий механик

# Насколько ярко светит каждый слой. Сумма держится заметно ниже
# единицы: метка на кнопке набрана костью (#E5DDCB), и если дать
# латуни разгореться, текст на ней перестанет читаться.
СИЛА_БЛИКА = 0.34
СИЛА_ВОЛНЫ = 0.26
ПОДСВЕТКА_РАМКИ = 0.30       # насколько рамка ярче под курсором
# Рамка под курсором ещё и дышит. Это не только красиво: Pillow
# ужимает кадр APNG до области, отличающейся от предыдущей, и при
# неподвижной рамке кадры выходили обрезанными до внутренней части
# (590 x 75 вместо 600 x 84). FancyMenu offset кадра не учитывает
# и растягивает обрезок на всю кнопку — рамка на наведённой кнопке
# просто пропадала. Живая рамка держит область кадра полной.
РАЗМАХ_ДЫХАНИЯ = 0.12


def _сетка(ширина, высота):
    """Нормированные координаты пикселей: x и y в долях стороны."""
    x = np.linspace(0.0, 1.0, ширина, dtype=np.float32)[None, :]
    y = np.linspace(0.0, 1.0, высота, dtype=np.float32)[:, None]
    return np.broadcast_to(x, (высота, ширина)), np.broadcast_to(y, (высота, ширина))


def _кадр(ширина, высота, толщина_рамки, фаза):
    """Один кадр наведённой кнопки. `фаза` — доля цикла от 0 до 1.

    Два слоя поверх плашки:

    - **блик** — широкая наклонная полоса латуни, проходящая слева
      направо; наклон берётся от `y`, поэтому полоса идёт диагональю
      и читается как перелив по металлу, а не как ползущая шторка;
    - **волна** — синусоида, бегущая в ту же сторону вдвое медленнее,
      с мягким свечением вдоль гребня. Она и даёт рябь внутри кнопки.

    Волна гасится к краям: у самой рамки светящийся гребень выглядел бы
    обрубленным.
    """
    x, y = _сетка(ширина, высота)

    ход = фаза * 1.6 - 0.3                      # блик выезжает и уезжает за край
    наклон = (y - 0.5) * 0.5
    блик = np.exp(-(((x - ход - наклон) / 0.20) ** 2))

    гребень = 0.5 + 0.16 * np.sin(2.0 * math.pi * (x * 2.2 - фаза))
    волна = np.exp(-(((y - гребень) / 0.16) ** 2))
    волна *= np.clip(np.sin(math.pi * x) * 1.4, 0.0, 1.0)   # затухание к краям

    сила = np.clip(блик * СИЛА_БЛИКА + волна * СИЛА_ВОЛНЫ, 0.0, 1.0)
    сила *= _виньетка(*сила.shape[::-1])
    сила = сила[:, :, None]

    фон = np.array(ФОН, dtype=np.float32)
    латунь = np.array(ЛАТУНЬ, dtype=np.float32)
    пиксели = фон + (латунь - фон) * сила

    дыхание = ПОДСВЕТКА_РАМКИ + РАЗМАХ_ДЫХАНИЯ * math.sin(2.0 * math.pi * фаза)
    return _обвести(пиксели, толщина_рамки, дыхание)


def _виньетка(ширина, высота, поле=10.0):
    """Гасит свечение у самой кромки, чтобы рамка не тонула в блике.

    Без неё блик доезжает до края и подсвеченная обводка перестаёт
    читаться — кнопка на светлых кадрах выглядит без рамки вовсе.
    """
    x = np.arange(ширина, dtype=np.float32)[None, :]
    y = np.arange(высота, dtype=np.float32)[:, None]
    до_края = np.minimum(np.minimum(x, ширина - 1 - x),
                         np.minimum(y, высота - 1 - y))
    return np.clip(до_края / поле, 0.0, 1.0)


def _обвести(пиксели, толщина, подсветка):
    """Латунная рамка по краю. `подсветка` осветляет её к белому."""
    цвет = np.array(ЛАТУНЬ, dtype=np.float32)
    цвет = цвет + (255.0 - цвет) * подсветка
    пиксели[:толщина, :] = цвет
    пиксели[-толщина:, :] = цвет
    пиксели[:, :толщина] = цвет
    пиксели[:, -толщина:] = цвет
    return Image.fromarray(np.clip(пиксели, 0, 255).astype(np.uint8), "RGB")


def нарисовать(ширина_точек, высота_точек, рамка_точек):
    """Пишет обе текстуры и возвращает пути к ним."""
    ш = ширина_точек * ПИКСЕЛЕЙ_В_ТОЧКЕ
    в = высота_точек * ПИКСЕЛЕЙ_В_ТОЧКЕ
    рамка = рамка_точек * ПИКСЕЛЕЙ_В_ТОЧКЕ
    ПАПКА.mkdir(parents=True, exist_ok=True)

    спокойная = np.tile(np.array(ФОН, dtype=np.float32), (в, ш, 1))
    _обвести(спокойная, рамка, 0.0).save(ОБЫЧНАЯ)

    кадры = [_кадр(ш, в, рамка, н / КАДРОВ) for н in range(КАДРОВ)]
    кадры[0].save(
        НАВЕДЁННАЯ,
        format="PNG",
        save_all=True,
        append_images=кадры[1:],
        duration=МС_НА_КАДР,
        loop=0,
    )
    return ОБЫЧНАЯ, НАВЕДЁННАЯ


if __name__ == "__main__":
    for файл in нарисовать(300, 42, 2):
        print("записано:", файл)
