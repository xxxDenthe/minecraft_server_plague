    м = Макет()

    # Фон и полосы. Ширина взята с запасом: у элементов FancyMenu нет
    # растягивания в свойствах, а лишнее просто уезжает за край экрана.
    м.прямоугольник(-2000, -2000, 4000, 4000, ФОН, прозрачность=0.94)
    м.прямоугольник(-2000, 0, 4000, ПОЛОСА_ВЕРХ, ПОЛОСА)
    м.прямоугольник(-2000, -ПОЛОСА_НИЗ, 4000, ПОЛОСА_НИЗ, ПОЛОСА,
                    привязка="bottom-centered")

    # Заголовок. Кегль — свойством `scale`, а не решёткой: решётка
    # тянет за собой подчёркивающую линию во всю ширину элемента.
    # Подписи под заголовком нет: владелец убрал её 2026-09-08.
    # Марка приглушённой латунью, название костью — чтобы первым
    # читалось слово, а не бренд сервера.
    высота_заголовка = ВЫСОТА_СТРОКИ * КЕГЛЬ_ЗАГОЛОВКА
    м.текст(-200, (ПОЛОСА_ВЕРХ - высота_заголовка) / 2, 400,
            высота_заголовка + 6,
            по_центру(цвет(МАРКА, АКЦЕНТ) + цвет(ЗАГОЛОВОК_ЭКРАНА, ЗАГОЛОВОК)),
            scale=str(КЕГЛЬ_ЗАГОЛОВКА))

    # Разделители колонок — посередине промежутков.
    for левый, ширина in zip(края[:-1], КОЛОНКИ_Ш[:-1]):
        м.прямоугольник(левый + ширина + ПРОМЕЖУТОК // 2, ШАПКА_Y, 1,
                        НИЗ_КОЛОНОК - ШАПКА_Y, ЛИНИЯ)

    # Шапки колонок.
    шапки = (ЛОР_ШАПКА, МЕХАНИКИ_ШАПКА, ПРАВИЛА_ШАПКА)
    for x, ширина, шапка in zip(края, КОЛОНКИ_Ш, шапки):
        м.текст(x, ШАПКА_Y, ширина, ВЫСОТА_СТРОКИ * КЕГЛЬ_ШАПОК + 4,
                по_центру("**" + цвет(шапка, ШАПКА) + "**"),
                scale=str(КЕГЛЬ_ШАПОК))

    # Колонка 1 — лор.
    м.текст(края[0], ТЕЛО_Y, КОЛОНКИ_Ш[0], НИЗ_КОЛОНОК - ТЕЛО_Y,
            строки([раскрасить(с) for с in ЛОР]), scale=str(кегль))

    # Колонка 2 — механики: иконка, название, объяснение. Шаг считается
    # из длины абзаца: они разной длины, и постоянный шаг либо режет
    # длинные пункты, либо оставляет дыры под короткими.
    y = float(ТЕЛО_Y)
    ширина_тела = КОЛОНКИ_Ш[1] - ОТСТУП_ТЕКСТА
    for ключ, название, объяснение in МЕХАНИКИ:
        м.предмет(края[1], y, ключ)
        м.текст(края[1] + ОТСТУП_ТЕКСТА, y, ширина_тела, строка + 4,
                "**" + цвет(название, АКЦЕНТ) + "**", scale=str(кегль))
        строк = строк_в_абзаце(объяснение, ширина_тела, кегль)
        м.текст(края[1] + ОТСТУП_ТЕКСТА, y + строка, ширина_тела,
                строка * строк + 4, цвет(объяснение, ТЕКСТ), scale=str(кегль))
        y += высота_пункта(объяснение, КОЛОНКИ_Ш[1], кегль) + ЗАЗОР_ПУНКТОВ

    # Колонка 3 — что знать сразу.
    м.текст(края[2], ТЕЛО_Y, КОЛОНКИ_Ш[2], НИЗ_КОЛОНОК - ТЕЛО_Y,
            строки([раскрасить(с) for с in ПРАВИЛА]), scale=str(кегль))

    # Кнопка.
    м.кнопка(0, КНОПКА_Y, КНОПКА_Ш, КНОПКА_В, КНОПКА)

    return м.в_текст(), кегль, высоты


