"""
Генератор стартового экрана для мода Welcome Screen (ElocinDev).

Экран рисует не сам Welcome Screen, а FancyMenu: мод только заводит два
пустых кастомных GUI (`welcomescreen_welcome` и `welcomescreen_update`)
и показывает первый при первом входе в мир. Всё содержимое — это макет
FancyMenu, обычный текстовый файл в `config/fancymenu/customization/`.

Руками такой файл писать нечитаемо: три колонки — это три десятка
однотипных блоков `element { ... }` с посчитанными координатами.
Поэтому текст экрана и его раскладка живут здесь, а `.txt` — производная.
Правим тут и перегенерируем:

    python launcher/tools/make-welcome-screen.py

Формат макета снят с байткода FancyMenu 3.9.12 (публичного описания
формата нет). Что важно знать, если придётся править `.txt` руками:

- Файл начинается со строки `type = fancymenu_layout`, дальше секции
  `layout-meta { ... }` и `element { ... }`.
- `identifier` в `layout-meta` — идентификатор экрана, у нас
  `welcomescreen_welcome`. Экран открывается и вручную:
  `/openguiscreen welcomescreen_welcome`.
- Перенос строки внутри значения пишется как `%n%`.
- У текстового элемента (`text_v2`) цвет задаётся разметкой внутри
  текста: `%#RRGGBB%…%#%` — цвет, `**…**` — жирный, `^^^…^^^` —
  центрирование. **Центрирование обязано закрываться**: одиночное
  `^^^` в начале строки FancyMenu печатает буквально (проверено в игре
  2026-09-08). В байткоде это `isFormattedBlock(line, '^', false)` —
  парсер ищет вторую тройку кареток.
- Кегль — это свойство элемента `scale`, а не разметка. Решётка `# `
  в начале строки тоже даёт заголовок, но с центрированием её
  сочетать незачем: `scale` проще и не спорит с кареткой.
- Координаты считаются от точки привязки (`anchor_point`). Мы держим
  всё на `top-centered` и `bottom-centered`, поэтому раскладка не
  разъезжается при другом разрешении и другом масштабе интерфейса.

Кегль тела подбирается автоматически — см. `подобрать_кегль` ниже.
Спек переделки под длинные тексты:
`docs/superpowers/specs/2026-09-08-startovyj-ekran-dlinnye-teksty-design.md`
"""

