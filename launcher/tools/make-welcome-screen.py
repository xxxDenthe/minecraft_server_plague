# ------------------------------------------------------------ сборка .txt

def цвет(текст, hex_без_решётки):
    """Разметка цвета FancyMenu: %#RRGGBB%…%#%."""
    return "%#" + hex_без_решётки + "%" + текст + "%#%"


def по_центру(текст):
    """Центрирование FancyMenu.

    Обе тройки кареток стоят на **своих собственных строках** — так
    в документации FancyMenu («^^^ before and after the lines»), и
    только так работает. Каретки, дописанные к строке текста
    (`^^^ЧУМА^^^` или `^^^ЧУМА%n%^^^`), печатаются буквально —
    проверено в игре 2026-09-08. Свои строки места не занимают:
    парсер их съедает целиком.
    """
    return "^^^%n%" + текст + "%n%^^^"


def строки(куски):
    """Абзацы -> одно значение свойства с переносами FancyMenu."""
    return "%n%".join(куски)


class Макет:
    def __init__(self):
        self.элементы = []
        self._счётчик = 0

    def ид(self, префикс):
        self._счётчик += 1
        return "lmpc_%s_%d" % (префикс, self._счётчик)

    def добавить(self, тип, свойства, префикс="el"):
        свойства = dict(свойства)
        свойства.setdefault("instance_identifier", self.ид(префикс))
        self.элементы.append((тип, свойства))

    # -- готовые виды элементов -------------------------------------

    def прямоугольник(self, x, y, w, h, цвет_hex, привязка="top-centered",
                      прозрачность=None):
        свойства = {
            "x": x, "y": y, "width": w, "height": h,
            "anchor_point": привязка,
            "color": цвет_hex,
        }
        if прозрачность is not None:
            свойства["base_opacity"] = прозрачность
        self.добавить("shape", свойства, "rect")

    def текст(self, x, y, w, h, содержимое, привязка="top-centered", **ещё):
        свойства = {
            "x": x, "y": y, "width": w, "height": h,
            "anchor_point": привязка,
            "source_mode": "direct",
            "source": содержимое,
            "parse_markdown": "true",
            "auto_line_wrapping": "true",
            "enable_scrolling": "false",
            "interactable": "false",
            "shadow": "true",
        }
        свойства.update(ещё)
        self.добавить("text_v2", свойства, "text")

    def предмет(self, x, y, ключ, привязка="top-centered"):
        self.добавить("item", {
            "x": x, "y": y, "width": ИКОНКА, "height": ИКОНКА,
            "anchor_point": привязка,
            "item_key": ключ,
            "show_tooltip": "false",
            "enchanted": "false",
        }, "item")

    def кнопка(self, x, y, w, h, подпись, привязка="bottom-centered"):
        блок = self.ид("block")
        действие = self.ид("act")
        self.добавить("custom_button", {
            "x": x, "y": y, "width": w, "height": h,
            "anchor_point": привязка,
            "sticky_anchor": "true",
            "label": подпись,
            "button_element_executable_block_identifier": блок,
            "[executable_block:%s][type:generic]" % блок:
                "[executables:%s;]" % действие,
            "[executable_action_instance:%s][action_type:closegui]" % действие: "",
        }, "button")

    # -- вывод -------------------------------------------------------

    def в_текст(self):
        части = ["type = fancymenu_layout", ""]
        части += [
            "layout-meta {",
            "  identifier = welcomescreen_welcome",
            "  is_enabled = true",
            "  randommode = false",
            "  randomonlyfirsttime = false",
            "  render_custom_elements_behind_vanilla = false",
            "  layout_index = 0",
            "  last_edited_time = %d" % int(time.time() * 1000),
            "}",
            "",
        ]
        for тип, свойства in self.элементы:
            части.append("element {")
            части.append("  element_type = %s" % тип)
            for ключ, значение in свойства.items():
                части.append("  %s = %s" % (ключ, значение))
            части.append("}")
            части.append("")
        return "\n".join(части)


def собрать():
    м = Макет()

    # Фон и полосы. Ширина взята с запасом: у элементов FancyMenu нет
    # растягивания в свойствах, а лишнее просто уезжает за край экрана.
    м.прямоугольник(-2000, -2000, 4000, 4000, ФОН, прозрачность=0.94)
    м.прямоугольник(-2000, 0, 4000, ПОЛОСА_ВЕРХ, ПОЛОСА)
    м.прямоугольник(-2000, -ПОЛОСА_НИЗ, 4000, ПОЛОСА_НИЗ, ПОЛОСА,
                    привязка="bottom-centered")

    # Заголовок. Кегль — свойством `scale`, а не решёткой: решётка
    # тянет за собой подчёркивающую линию во всю ширину элемента.
    # Подписи под заголовком нет: владелец убрал её 2026-09-08.
    # Заголовок поэтому опущен к середине верхней полосы.
    м.текст(-200, 14, 400, 26, по_центру(цвет(ЗАГОЛОВОК_ЭКРАНА, ЗАГОЛОВОК)),
            scale="2.0")

    # Разделители колонок.
    for x in РАЗДЕЛИТЕЛИ_X:
        м.прямоугольник(x, ШАПКА_Y, 1, НИЗ_КОЛОНОК - ШАПКА_Y, ЛИНИЯ)

    # Шапки колонок.
    for x, шапка in zip(КОЛОНКИ_X, (ЛОР_ШАПКА, МЕХАНИКИ_ШАПКА, ПРАВИЛА_ШАПКА)):
        м.текст(x, ШАПКА_Y, КОЛОНКА, 14,
                по_центру("**" + цвет(шапка, ШАПКА) + "**"))

    # Колонка 1 — лор.
    м.текст(КОЛОНКИ_X[0], ТЕЛО_Y, КОЛОНКА, НИЗ_КОЛОНОК - ТЕЛО_Y,
            строки([цвет(с, ТЕКСТ) if с else "" for с in ЛОР]))

    # Колонка 2 — механики: иконка, название, объяснение.
    for н, (предмет, название, объяснение) in enumerate(МЕХАНИКИ):
        y = ТЕЛО_Y + н * ШАГ
        м.предмет(КОЛОНКИ_X[1], y, предмет)
        # Высота 14, а не 10: при 12 у строки срезало хвосты «у» и «р».
        м.текст(КОЛОНКИ_X[1] + ОТСТУП_ТЕКСТА, y,
                КОЛОНКА - ОТСТУП_ТЕКСТА, 14,
                "**" + цвет(название, АКЦЕНТ) + "**")
        м.текст(КОЛОНКИ_X[1] + ОТСТУП_ТЕКСТА, y + 13,
                КОЛОНКА - ОТСТУП_ТЕКСТА, ШАГ - 13,
                цвет(объяснение, ТЕКСТ))

    # Колонка 3 — что знать сразу.
    м.текст(КОЛОНКИ_X[2], ТЕЛО_Y, КОЛОНКА, НИЗ_КОЛОНОК - ТЕЛО_Y,
            строки([цвет(с, ТЕКСТ) if с else "" for с in ПРАВИЛА]))

    # Кнопка.
    м.кнопка(0, -30, 150, 20, КНОПКА)

    return м.в_текст()


