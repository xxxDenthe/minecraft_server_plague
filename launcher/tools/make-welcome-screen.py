# --------------------------------------------------------- обмер текста
#
# FancyMenu переносит текст сам, а мы должны заранее знать, влезет ли
# колонка: вылезший хвост лора виден только в запущенной игре, а цикл
# «правка → снимок» стоит две минуты. Поэтому меряем здесь.
#
# Числа откалиброваны по снимку из игры (2026-09-08), а не взяты на глаз:
# строка «утверждало, что отвар местного клирика» ровно заполняет колонку
# шириной 178 точек при кегле 0.7. Отсюда семь точек на знак кириллицы
# (шесть на глиф плюс отступ) и четыре на пробел и пунктуацию. Прежняя
# шестёрка была занижена, и три абзаца из десяти уезжали за нижний край.
#
# Жирный в шрифте Minecraft рисуется двойным проходом со сдвигом, то есть
# каждый знак шире на точку. В правой колонке жирного много, и без этой
# поправки последний пункт срезало.

УЗКИЕ = set(" .,:;!|iltjfI()[]'")
ШИРИНА_ЗНАКА = 7
ШИРИНА_УЗКОГО = 4
ПРИБАВКА_ЖИРНОГО = 1
# Высота строки замерена по снимку из игры (2026-09-08): при кегле 0.75
# соседние строки отстояли на девять точек, то есть двенадцать при кегле
# единица. Прежняя десятка была взята на глаз, и из-за неё три колонки
# из трёх вылезали за свои границы.
ВЫСОТА_СТРОКИ = 12


def ширина_текста(текст, жирный=False):
    """Ширина куска строки в точках при кегле 1.0.

    Разметка `**` не печатается, но переключает жирность, а жирный знак
    шире обычного на точку. Возвращает ширину и жирность на конце куска,
    чтобы следующее слово считалось в том же начертании.
    """
    ширина = 0
    куски = текст.split("**")
    for н, кусок in enumerate(куски):
        if н:
            жирный = not жирный
        for з in кусок:
            ширина += ШИРИНА_УЗКОГО if з in УЗКИЕ else ШИРИНА_ЗНАКА
            if жирный:
                ширина += ПРИБАВКА_ЖИРНОГО
    return ширина, жирный


def строк_в_абзаце(текст, ширина, кегль):
    """Сколько строк займёт абзац в колонке заданной ширины."""
    if not текст:
        return 1
    предел = ширина / кегль
    строк, текущая, жирный = 1, 0.0, False
    for слово in текст.split():
        w, жирный = ширина_текста(слово, жирный)
        пробел = ШИРИНА_УЗКОГО if текущая else 0
        if текущая and текущая + пробел + w > предел:
            строк += 1
            текущая = w
        else:
            текущая += пробел + w
    return строк


def высота_абзацев(абзацы, ширина, кегль):
    """Высота простой колонки текста в точках."""
    строк = sum(строк_в_абзаце(а, ширина, кегль) for а in абзацы)
    return строк * ВЫСОТА_СТРОКИ * кегль


def высота_пункта(объяснение, ширина, кегль):
    """Высота одного пункта средней колонки: шапка плюс абзац.

    Не меньше иконки: пункт с одной строкой объяснения всё равно
    занимает высоту своей картинки.
    """
    строка = ВЫСОТА_СТРОКИ * кегль
    строк = строк_в_абзаце(объяснение, ширина - ОТСТУП_ТЕКСТА, кегль)
    return max(строка * (1 + строк), ИКОНКА)


def высота_пунктов(ширина, кегль):
    """Высота всей средней колонки вместе с зазорами между пунктами."""
    высоты = [высота_пункта(о, ширина, кегль) for _, _, о in МЕХАНИКИ]
    return sum(высоты) + ЗАЗОР_ПУНКТОВ * (len(высоты) - 1)


def подобрать_кегль():
    """Самый крупный кегль, при котором все три колонки влезают.

    Тексты экрана владелец правит регулярно, и подгонять координаты
    руками после каждой правки — работа на ровном месте. Пусть считает
    скрипт; а если не влезает даже на самом мелком кегле, пусть падает
    здесь, а не обнаруживается в игре через две минуты.
    """
    место = НИЗ_КОЛОНОК - ТЕЛО_Y
    высоты = ()
    for кегль in КЕГЛИ:
        высоты = (
            высота_абзацев(ЛОР, КОЛОНКИ_Ш[0], кегль),
            высота_пунктов(КОЛОНКИ_Ш[1], кегль),
            высота_абзацев(ПРАВИЛА, КОЛОНКИ_Ш[2], кегль),
        )
        if max(высоты) <= место:
            return кегль, высоты
    raise AssertionError(
        "текст не влезает в колонки даже кеглем %.2f: колонкам нужно %s "
        "точек, есть %d. Сократить текст или пересмотреть ширины колонок."
        % (КЕГЛИ[-1], ["%.0f" % в for в in высоты], место)
    )


def края_колонок():
    """Левые края трёх колонок, считая от центра экрана."""
    полная = sum(КОЛОНКИ_Ш) + ПРОМЕЖУТОК * (len(КОЛОНКИ_Ш) - 1)
    assert полная <= ЭКРАН_Ш, "колонки шире экрана: %d > %d" % (полная, ЭКРАН_Ш)
    x = -(полная // 2)
    края = []
    for ш in КОЛОНКИ_Ш:
        края.append(x)
        x += ш + ПРОМЕЖУТОК
    return края


# ------------------------------------------------------------ сборка .txt

def цвет(текст, hex_без_решётки):
    """Разметка цвета FancyMenu: %#RRGGBB%…%#%."""
    return "%#" + hex_без_решётки + "%" + текст + "%#%"


def по_центру(текст):
    """Центрирование FancyMenu.

    Обе тройки кареток стоят на **своих собственных строках** — так
    в документации FancyMenu («^^^ before and after the lines»), и
    только так работает. Каретки, дописанные к строке текста
    (`^^^ЧУМА^^^` или `^^^ЧУМА%n%^^^`), печатаются буквально —
    проверено в игре 2026-09-08. Свои строки места не занимают:
    парсер их съедает целиком.
    """
    return "^^^%n%" + текст + "%n%^^^"


def строки(куски):
    """Абзацы -> одно значение свойства с переносами FancyMenu."""
    return "%n%".join(куски)


def раскрасить(абзац):
    """Тело колонки: серый текст, жирные куски внутри остаются жирными."""
    return цвет(абзац, ТЕКСТ) if абзац else ""


class Макет:
    def __init__(self):
        self.элементы = []
        self._счётчик = 0

    def ид(self, префикс):
        self._счётчик += 1
        return "lmpc_%s_%d" % (префикс, self._счётчик)

    def добавить(self, тип, свойства, префикс="el"):
        свойства = dict(свойства)
        свойства.setdefault("instance_identifier", self.ид(префикс))
        self.элементы.append((тип, свойства))

    # -- готовые виды элементов -------------------------------------

    def прямоугольник(self, x, y, w, h, цвет_hex, привязка="top-centered",
                      прозрачность=None):
        свойства = {
            "x": int(x), "y": int(y), "width": int(w), "height": int(h),
            "anchor_point": привязка,
            "color": цвет_hex,
        }
        if прозрачность is not None:
            свойства["base_opacity"] = прозрачность
        self.добавить("shape", свойства, "rect")

    def текст(self, x, y, w, h, содержимое, привязка="top-centered", **ещё):
        свойства = {
            "x": int(x), "y": int(y), "width": int(w), "height": int(h),
            "anchor_point": привязка,
            "source_mode": "direct",
            "source": содержимое,
            "parse_markdown": "true",
            "auto_line_wrapping": "true",
            "enable_scrolling": "false",
            "interactable": "false",
            "shadow": "true",
        }
        свойства.update(ещё)
        self.добавить("text_v2", свойства, "text")

    def предмет(self, x, y, ключ, привязка="top-centered"):
        self.добавить("item", {
            "x": int(x), "y": int(y), "width": ИКОНКА, "height": ИКОНКА,
            "anchor_point": привязка,
            "item_key": ключ,
            "show_tooltip": "false",
            "enchanted": "false",
        }, "item")

    def кнопка(self, x, y, w, h, подпись, привязка="bottom-centered"):
        блок = self.ид("block")
        действие = self.ид("act")
        self.добавить("custom_button", {
            "x": int(x), "y": int(y), "width": int(w), "height": int(h),
            "anchor_point": привязка,
            "sticky_anchor": "true",
            "label": подпись,
            "button_element_executable_block_identifier": блок,
            "[executable_block:%s][type:generic]" % блок:
                "[executables:%s;]" % действие,
            "[executable_action_instance:%s][action_type:closegui]" % действие: "",
        }, "button")

    # -- вывод -------------------------------------------------------

    def в_текст(self):
        части = ["type = fancymenu_layout", ""]
        части += [
            "layout-meta {",
            "  identifier = welcomescreen_welcome",
            "  is_enabled = true",
            "  randommode = false",
            "  randomonlyfirsttime = false",
            "  render_custom_elements_behind_vanilla = false",
            "  layout_index = 0",
            "  last_edited_time = %d" % int(time.time() * 1000),
            "}",
            "",
        ]
        for тип, свойства in self.элементы:
            части.append("element {")
            части.append("  element_type = %s" % тип)
            for ключ, значение in свойства.items():
                части.append("  %s = %s" % (ключ, значение))
            части.append("}")
            части.append("")
        return "\n".join(части)


def собрать():
    кегль, высоты = подобрать_кегль()
    края = края_колонок()
