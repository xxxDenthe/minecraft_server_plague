#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Текстура очистителя — производная от настоящего ассета Create.

Курс проекта (docs/superpowers/notes/2026-09-06-create-style-kurs.md)
требует, чтобы модели и текстуры отталкивались от Create, а не рисовались
с нуля, и — второй половиной того же правила — чтобы **готовая текстура
Create была предпочтительнее своей производной**. Поэтому производных
тут осталось ровно столько, сколько у Create аналога нет: одна.

Из джарника Create берётся один файл:

    block/andesite_casing   оправа андезитового тира

и делается три:

    andesite_purifier_casing.png   тулово и сопло андезитового, в холодный серый
    brass_purifier_band.png        пояса латунного
    brass_purifier_plate.png       верх и низ головы латунного

Андезитовое обесцвечивание нужно, потому что коричневая голова на
коричневой оправе слипалась в один комод, а серая делит блок на ярусы
глазом. Готового «обесцвеченного андезитового корпуса» у Create нет.

Латунные две — следствие решения владельца от 2026-09-07: оба тира носят
одну форму, «корпус машины». Форма держится на `mixer_base_side`
и `mechanical_press_top`, а латунных версий этих двух текстур у Create
нет — есть только ровная оправа `brass_casing`. Латунный вышел бы гладким
там, где андезитовый рифлёный, и тиры читались бы как разные машины.

Делаются они не рисованием, а **переносом правки**. И `mixer_base_side`,
и `mechanical_press_top` — это `andesite_casing`, у которой середина
переделана: у первой выглажена в плоскую панель, у второй прорисована
плитой пресса. Рамка у всех трёх файлов совпадает пиксель в пиксель.
Значит, отношение «стало / было» по светимости и есть сама правка, и его
можно наложить на `brass_casing`, сохранив латунный цвет. Там, где Create
ничего не менял, отношение равно единице и латунная оправа остаётся собой
буквально, без округлений.

Голова латунного производной по-прежнему не требует:
`create:block/brass_block` — настоящая полированная латунь (в среднем
200·155·89 против 117·85·48 у оправы), модель ссылается на неё напрямую.

Гнёзд вала здесь тоже больше нет. Своё гнездо было нарисовано под вал
6×6, тогда как настоящий вал Create — 4×4 (`shaft.json`: [6,0,6] →
[10,16,10]). Вместо перерисовки взяты готовые `create:block/gearbox`
и `create:block/brass_gearbox`: они нарисованы ровно под вал 4×4 и уже
содержат фаску. См.
docs/superpowers/notes/2026-09-07-blockbench-create-style-rukovodstvo.md

Запуск (из корня репозитория):

    python textures_src/create_sprayer/make_purifier_textures.py

Готовый PNG кладётся сразу и в assets мода, и в textures_src рядом
со скриптом — второй нужен, чтобы источник правки был виден без сборки.
"""

import io
import os
import zipfile

from PIL import Image

КОРЕНЬ = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ДЖАР = os.path.join(КОРЕНЬ, "mods", "create-1.21.1-6.0.10.jar")
АССЕТЫ = os.path.join(КОРЕНЬ, "lmpc_classes", "src", "main", "resources",
                      "assets", "lmpc_classes", "textures", "block")
ИСХОДНИКИ = os.path.dirname(os.path.abspath(__file__))

# Тон умножается на светимость пикселя, поэтому рисунок оправы
# сохраняется, а цвет задаётся заново. Синего чуть больше единицы,
# красного чуть меньше — оттого голова уходит в холодный серый.
ТОН = (0.93, 0.97, 1.05)


def читать(имя):
    """Текстура блока из джарника Create, по короткому имени без пути."""
    with zipfile.ZipFile(ДЖАР) as джар:
        данные = джар.read("assets/create/textures/block/%s.png" % имя)
    return Image.open(io.BytesIO(данные)).convert("RGBA")


def тонировать(картинка, тон=ТОН):
    """Обесцветить до светимости и залить своим тоном."""
    r_к, g_к, b_к = тон
    итог = картинка.copy()
    пиксели = итог.load()
    ширина, высота = итог.size
    for y in range(высота):
        for x in range(ширина):
            r, g, b, a = пиксели[x, y]
            свет = светимость((r, g, b))
            пиксели[x, y] = (
                min(255, int(свет * r_к)),
                min(255, int(свет * g_к)),
                min(255, int(свет * b_к)),
                a,
            )
    return итог


def перенести(основа, было, стало):
    """Наложить правку «было → стало» на другую основу, сохранив её цвет.

    Отношение светимостей — это ровно то, что Create сделал с оправой:
    выгладил середину или прорисовал плиту. Цвет берётся у основы,
    прозрачность — у результата правки (у `mixer_base_side` две нижние
    строки прозрачны, и это важно для окон UV).
    """
    итог = основа.copy()
    п_итог, п_основа = итог.load(), основа.load()
    п_было, п_стало = было.load(), стало.load()
    ширина, высота = итог.size
    for y in range(высота):
        for x in range(ширина):
            r, g, b, _ = п_основа[x, y]
            к = светимость(п_стало[x, y]) / max(1.0, светимость(п_было[x, y]))
            п_итог[x, y] = (min(255, int(r * к)), min(255, int(g * к)),
                            min(255, int(b * к)), п_стало[x, y][3])
    return итог


def светимость(пиксель):
    r, g, b = пиксель[:3]
    return 0.299 * r + 0.587 * g + 0.114 * b


def самопроверка():
    """Голова обязана остаться той же картинкой, но холоднее оправы.

    Проверка дешёвая, но ловит две настоящие ошибки: съехавшую
    прозрачность (тогда модель начнёт просвечивать) и тон, который
    развернулся в тёплую сторону — ради чего всё и затевалось.
    """
    оправа = читать("andesite_casing")
    голова = тонировать(оправа)
    for y in range(16):
        for x in range(16):
            assert оправа.getpixel((x, y))[3] == голова.getpixel((x, y))[3], \
                "прозрачность съехала в %d,%d" % (x, y)
    видимые = [(x, y) for y in range(16) for x in range(16)
               if оправа.getpixel((x, y))[3] > 0]
    def перекос(картинка):
        сумма = [sum(картинка.getpixel(т)[к] for т in видимые) for к in range(3)]
        return сумма[2] - сумма[0]          # синий минус красный
    assert перекос(голова) > перекос(оправа), "голова не стала холоднее оправы"

    # Перенос правки обязан быть тождественным там, где правки не было:
    # рамка у mixer_base_side и andesite_casing совпадает, значит и пояс
    # обязан там совпасть с brass_casing до пикселя. Это ловит и съехавший
    # порядок аргументов, и потерянную прозрачность нижних строк.
    латунь = читать("brass_casing")
    панель = читать("mixer_base_side")
    пояс = перенести(латунь, оправа, панель)
    совпало = 0
    for y in range(16):
        for x in range(16):
            if панель.getpixel((x, y)) == оправа.getpixel((x, y)):
                assert пояс.getpixel((x, y)) == латунь.getpixel((x, y)),                     "рамка поехала в %d,%d" % (x, y)
                совпало += 1
    assert совпало > 100, "рамки почти не совпали, перенос делать не на чем"
    assert пояс.getpixel((0, 15))[3] == 0, "прозрачность нижних строк потерялась"
    print("самопроверка: голова холоднее оправы, перенос правки тождественный")


def собрать():
    андезит = читать("andesite_casing")
    латунь = читать("brass_casing")
    файлы = {
        "andesite_purifier_casing.png": тонировать(андезит),
        "brass_purifier_band.png":
            перенести(латунь, андезит, читать("mixer_base_side")),
        "brass_purifier_plate.png":
            перенести(латунь, андезит, читать("mechanical_press_top")),
    }
    for папка in (АССЕТЫ, ИСХОДНИКИ):
        for имя, картинка in файлы.items():
            картинка.save(os.path.join(папка, имя))
    print("собрано: %s" % ", ".join(sorted(файлы)))


if __name__ == "__main__":
    самопроверка()
    собрать()
