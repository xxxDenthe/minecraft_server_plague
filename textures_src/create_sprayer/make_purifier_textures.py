#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Текстуры очистителя — производные от настоящих ассетов Create.

Курс проекта (docs/superpowers/notes/2026-09-06-create-style-kurs.md)
требует, чтобы модели и текстуры отталкивались от Create, а не рисовались
с нуля. Андезитовый тир так и сделан, но вручную: рецепт жил только
в заметке, и повторить его для латуни означало бы угадывать числа заново.
Скрипт превращает рецепт в код.

Из джарника Create берутся три файла:

    block/andesite_casing   оправа андезитового тира
    block/brass_casing      оправа латунного тира
    block/axis_top          торец вала — вкладывается в гнездо

и делаются два файла на тир:

    <тир>_purifier_casing.png   голова: тулово, венец и сопло
    <тир>_purifier_socket.png   нижняя грань оправы с гнездом вала

Запуск (из корня репозитория):

    python textures_src/create_sprayer/make_purifier_textures.py

Готовые PNG кладутся сразу и в assets мода, и в textures_src рядом
со скриптом — вторые нужны, чтобы источник правки был виден без сборки.

Одна честная оговорка про андезит. Его две текстуры были сделаны руками
раньше скрипта, и лежащие в репозитории файлы — те, рукодельные.
Скрипт повторяет их рецепт: голова выходит пиксель в пиксель, а гнездо
расходится на один продублированный ряд в торце вала — нежное место
растяжки 4 × 4 до 6 × 6, где выбор повторяемого ряда произволен.
Разница не видна глазом, но перезапуск скрипта покажет андезитовые
файлы изменёнными. Это ожидаемо, а не поломка.
"""

import io
import os
import zipfile

from PIL import Image

КОРЕНЬ = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ДЖАР = os.path.join(КОРЕНЬ, "mods", "create-1.21.1-6.0.10.jar")
АССЕТЫ = os.path.join(КОРЕНЬ, "lmpc_classes", "src", "main", "resources",
                      "assets", "lmpc_classes", "textures", "block")
ИСХОДНИКИ = os.path.dirname(os.path.abspath(__file__))

# Гнездо вала: чёрное отверстие 8×8 в центре грани, в него вложен торец
# вала 6×6. Числа канонические — у крейтовского вала торец ровно 6×6.
ОТВЕРСТИЕ = (4, 4, 12, 12)
ТОРЕЦ = (5, 5, 11, 11)

# Во сколько раз темнеет оправа внутри отверстия. Не чистый чёрный:
# полная заливка выглядит дырой в пустоту, а не углублением в металле.
ТЕНЬ = 0.22

# Тир → (оправа в Create, тон головы). Тон умножается на светимость
# пикселя, поэтому рисунок оправы сохраняется, а цвет задаётся заново.
#
# Правило владельца: **готовая текстура Create всегда лучше своей
# производной**, и делать производную стоит только там, где у Create
# подходящей нет. Отсюда разные строчки у двух тиров.
#
# Андезит производную требует: голова уводится в холодный серый, потому
# что коричневая голова на коричневой оправе слипалась в один комод,
# а серая делит блок на ярусы глазом. Готового «обесцвеченного
# андезитового корпуса» у Create нет.
#
# Латуни производная не нужна: `create:block/brass_block` — настоящая
# полированная латунь (в среднем 200·155·89 против 117·85·48 у оправы),
# то есть ровно та светлая голова на тёмном корпусе, которая тут
# и требуется. Модель ссылается на неё прямо, `None` означает
# «голову не делаем».
ТИРЫ = {
    "andesite": ("andesite_casing", (0.93, 0.97, 1.05)),
    "brass": ("brass_casing", None),
}


def читать(имя):
    """Текстура блока из джарника Create, по короткому имени без пути."""
    with zipfile.ZipFile(ДЖАР) as джар:
        данные = джар.read("assets/create/textures/block/%s.png" % имя)
    return Image.open(io.BytesIO(данные)).convert("RGBA")


def тонировать(картинка, тон):
    """Обесцветить до светимости и залить своим тоном."""
    r_к, g_к, b_к = тон
    итог = картинка.copy()
    пиксели = итог.load()
    ширина, высота = итог.size
    for y in range(высота):
        for x in range(ширина):
            r, g, b, a = пиксели[x, y]
            свет = 0.299 * r + 0.587 * g + 0.114 * b
            пиксели[x, y] = (
                min(255, int(свет * r_к)),
                min(255, int(свет * g_к)),
                min(255, int(свет * b_к)),
                a,
            )
    return итог


def гнездо(оправа, торец):
    """Оправа с вырубленным отверстием и вложенным торцом вала."""
    итог = оправа.copy()
    пиксели = итог.load()
    x0, y0, x1, y1 = ОТВЕРСТИЕ
    for y in range(y0, y1):
        for x in range(x0, x1):
            r, g, b, a = пиксели[x, y]
            пиксели[x, y] = (int(r * ТЕНЬ), int(g * ТЕНЬ), int(b * ТЕНЬ), a)

    # Торец вала в axis_top — непрозрачный квадрат 4×4 посередине
    # прозрачного файла. Берём именно его и растягиваем до 6×6:
    # масштабировать весь файл значило бы тянуть и пустоту вокруг.
    ядро = торец.crop(торец.getbbox())
    ширина = ТОРЕЦ[2] - ТОРЕЦ[0]
    итог.paste(ядро.resize((ширина, ширина), Image.NEAREST), ТОРЕЦ[:2])
    return итог


def собрать(тир):
    имя_оправы, тон = ТИРЫ[тир]
    оправа = читать(имя_оправы)
    файлы = {"%s_purifier_socket.png" % тир: гнездо(оправа, читать("axis_top"))}
    if тон is not None:
        файлы["%s_purifier_casing.png" % тир] = тонировать(оправа, тон)

    for папка in (АССЕТЫ, ИСХОДНИКИ):
        for имя, картинка in файлы.items():
            картинка.save(os.path.join(папка, имя))
    print("%s: из %s собрано %s" % (тир, имя_оправы, ", ".join(sorted(файлы))))


def самопроверка():
    """Гнездо обязано отличаться от оправы ровно в отверстии, и нигде больше.

    Проверка дешёвая, но ловит две настоящие ошибки: съехавшие координаты
    отверстия и торец вала, который не попал внутрь (тогда центр гнезда
    совпал бы с затемнённой оправой).
    """
    оправа = читать("andesite_casing")
    порт = гнездо(оправа, читать("axis_top"))
    x0, y0, x1, y1 = ОТВЕРСТИЕ
    for y in range(16):
        for x in range(16):
            внутри = x0 <= x < x1 and y0 <= y < y1
            отличается = порт.getpixel((x, y)) != оправа.getpixel((x, y))
            assert внутри == отличается, "пиксель %d,%d" % (x, y)
    # Центр — торец вала, он светлее затемнённой оправы вокруг.
    центр = sum(порт.getpixel((8, 8))[:3])
    угол = sum(порт.getpixel((4, 4))[:3])
    assert центр > угол, "торец вала не лёг в отверстие"
    print("самопроверка: гнездо на месте")


if __name__ == "__main__":
    самопроверка()
    for тир in ТИРЫ:
        собрать(тир)
