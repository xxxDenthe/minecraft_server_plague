# ── рамка подсказок Legendary Tooltips ──────────────────────────────
#
# Лист 128 × 48: каждая рамка — четыре куска по 16 × 16 в одной строке
# (левый край, верх, низ, правый край), уровни идут строками вниз.
# Сам контур рисует мод цветом из конфига; в текстуре живёт только
# накладной узор — у нас это латунная скоба с заклёпкой по углам,
# та же, что держит планшет лазарета.

def рамка_подсказок():
    им = Image.new("RGBA", (128, 128), (0, 0, 0, 0))
    px = им.load()

    def скоба(кx, кy, дx, дy):
        """Уголок в 6 пикселей: две латунные черты и заклёпка на сгибе."""
        for i in range(6):
            px[кx + дx * i, кy] = ЛАТУНЬ[1] + (255,)
            px[кx, кy + дy * i] = ЛАТУНЬ[1] + (255,)
        px[кx + дx, кy + дy] = ЛАТУНЬ[0] + (255,)
        px[кx + дx * 2, кy + дy * 2] = ЛАТУНЬ[3] + (255,)

    # ячейка 0 — левый край: скобы смотрят внутрь сверху и снизу
    скоба(1, 1, 1, 1)
    скоба(1, 14, 1, -1)
    # ячейка 3 — правый край, зеркально
    скоба(62, 1, -1, 1)
    скоба(62, 14, -1, -1)
    # ячейки 1 и 2 — верх и низ: одна заклёпка посередине, не больше.
    # Узор по всей длине повторялся бы на широких подсказках JEI.
    for кx in (16, 32):
        px[кx + 8, 1 if кx == 16 else 14] = ЛАТУНЬ[0] + (255,)
        px[кx + 8, 2 if кx == 16 else 13] = ЛАТУНЬ[2] + (255,)
    return им


