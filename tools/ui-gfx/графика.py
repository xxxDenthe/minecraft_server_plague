def перекрасить_кнопку(им, сид, поле, обводка, порог=200):
    """Кнопка: тело кожей, ванильная обводка — своим цветом.

    `порог` — с какой яркости пиксель считается обводкой. Двести годится
    почти везде: светлее только белая фаска и глифы вроде замка и
    крестика. Полю ввода порог опускают — его рамка всего лишь серая.
    """
    им = им.convert("RGBA")
    ш, в = им.size
    rnd = random.Random(сид)
    крупно = поле_шума(rnd, (ш, в), max(3, min(ш, в) // 2), 60, 196)
    мелко = поле_шума(rnd, (ш, в), max(4, min(ш, в)), 92, 164)
    px = им.load()
    for y in range(в):
        for x in range(ш):
            r, g, b, a = px[x, y]
            if a == 0:
                continue
            L, _ = _ключ((r, g, b))
            if L >= порог:
                px[x, y] = обводка + (a,)
            elif L <= 20:
                px[x, y] = КРАЙ + (a,)
            else:
                v = (крупно[x, y] * 0.45 + мелко[x, y] * 0.55 - 78) / 108 * 1.6
                px[x, y] = тон(поле, v, x, y) + (a,)
    return им


def скобы_кнопки(им):
    """Латунные скобы по торцам большой кнопки — мелкая родня оковки окна.

    Кнопка растягивается игрой по ширине, и уцелеет только то, что лежит
    в «уголках» девятислойной нарезки. Поэтому скоба держится в шести
    пикселях от каждого торца, а нарезка расширена до шести своей
    `.mcmeta` (у ванили там три). Уже двенадцати пикселей кнопок не
    бывает, так что схлопнуться скобам негде.
    """
    ш, в = им.size
    px = им.load()

    def кисть(x, y, цвет):
        px[x, y] = цвет + (px[x, y][3],)

    for кx, дx in ((0, 1), (ш - 1, -1)):
        внутрь = кx + дx * 5                      # черта, отделяющая накладку
        for y in range(1, в - 1):
            кисть(внутрь, y, ЛАТУНЬ[2])
        for y in (1, в - 2):                      # верх и низ накладки
            for i in range(1, 6):
                кисть(кx + дx * i, y, ЛАТУНЬ[1])
        for y in (3, в - 4):                      # две заклёпки на накладке
            кисть(кx + дx * 2, y, ЛАТУНЬ[0])
            кисть(кx + дx * 3, y, ЛАТУНЬ[3])
    return им


def заклепать(им):
    """Латунная заклёпка в каждом углу — узор мелких кнопок.

    Целую скобу в двадцать пикселей не втиснуть, а точка с тенью читается
    даже на галочке и роднит мелочь с окнами. Угол, который прозрачен
    (стрелки страниц, ручка ползунка), заклёпке держаться не даёт.
    """
    ш, в = им.size
    if ш < 12 or в < 12:
        return им
    px = им.load()
    for x, y, дx, дy in ((1, 1, 1, 1), (ш - 2, 1, -1, 1),
                         (1, в - 2, 1, -1), (ш - 2, в - 2, -1, -1)):
        if px[x, y][3] < 128:
            continue
        px[x, y] = ЛАТУНЬ[0] + (px[x, y][3],)
        px[x + дx, y + дy] = ЛАТУНЬ[3] + (px[x + дx, y + дy][3],)
    return им


def перекрасить_панель(им, сид):
    """Нижняя панель: структуру здесь несёт не яркость, а прозрачность.

    Сквозные пиксели — это поле панели и донья слотов, за ними видно мир;
    непрозрачные — фаски и обводка. Красить их одним правилом по яркости
    нельзя: чёрная обводка и тёмное поле неразличимы по свету, но это
    разные вещи.
    """
    им = им.convert("RGBA")
    ш, в = им.size
    rnd = random.Random(сид)
    крупно = поле_шума(rnd, (ш, в), max(3, min(ш, в) // 2), 60, 196)
    мелко = поле_шума(rnd, (ш, в), max(4, min(ш, в)), 92, 164)
    px = им.load()
    for y in range(в):
        for x in range(ш):
            r, g, b, a = px[x, y]
            if a == 0:
                continue
            v = (крупно[x, y] * 0.45 + мелко[x, y] * 0.55 - 78) / 108 * 2.0
            if a < 255:
                px[x, y] = тон(ОКНО_Т, v, x, y) + (a,)
                continue
            # Обойма панели светлее, чем оправа окна: за панелью не
            # кожаный планшет, а живой мир, и на нём тёмное по тёмному
            # перестаёт читаться — слоты сливаются в одну полосу.
            L, _ = _ключ((r, g, b))
            if L >= 130:
                px[x, y] = _лз.ШОВ + (a,)
            elif L >= 55:
                px[x, y] = СВЕТЛО + (a,)
            else:
                px[x, y] = КРАЙ + (a,)
    return им


def обшить_панель(им):
    """Шов и латунные углы по внешнему ободу панели.

    Поля у панели ровно один пиксель — слоты прижаты к краю вплотную.
    Весь узор живёт в этом ободке: стежок через четыре пикселя сверху и
    снизу, в углах — латунная скоба в два пикселя на сторону.
    """
    ш, в = им.size
    px = им.load()
    for x in range(4, ш - 4, 4):
        for y in (0, в - 1):
            px[x, y] = _лз.ШОВ + (px[x, y][3],)
    for кx, дx in ((0, 1), (ш - 1, -1)):
        for кy, дy in ((0, 1), (в - 1, -1)):
            for i in range(2):
                px[кx + дx * i, кy] = ЛАТУНЬ[0] + (255,)
                px[кx, кy + дy * i] = ЛАТУНЬ[0] + (255,)
    return им


