def _ключ(цвет):
    """Яркость и насыщенность: по ним и решается, чем красить пиксель."""
    r, g, b = цвет[:3]
    return 0.299 * r + 0.587 * g + 0.114 * b, max(r, g, b) - min(r, g, b)


def перекрасить(им, сид, границы=(235, 168, 100, 66), поле=КОЖА,
                врезка=ОКНО_Т, беречь_цвет=True, сила=3.0):
    """Ванильный серый каркас → кожа лазарета, по яркости пикселя.

    Ванильные окна собраны из ровно четырёх серых: поле 198, дно слота
    139, тень 85/55 и белая фаска 255. Пороги ниже разводят их по
    ступеням нашей палитры, а шум с дизерингом добавляет коже зерно.

    `беречь_цвет` оставляет насыщенные пиксели нетронутыми: огонь под
    печью, пузыри варки и полоса опыта — это показания приборов,
    а не оправа, и перекрашивать их значит ломать читаемость.
    """
    им = им.convert("RGBA")
    ш, в = им.size
    rnd = random.Random(сид)
    крупно = поле_шума(rnd, (ш, в), max(3, min(ш, в) // 8), 60, 196)
    мелко = поле_шума(rnd, (ш, в), max(6, min(ш, в) // 3), 92, 164)
    px = им.load()
    бел, сер, тень, чернь = границы

    for y in range(в):
        for x in range(ш):
            r, g, b, a = px[x, y]
            if a == 0:
                continue
            L, нас = _ключ((r, g, b))
            if беречь_цвет and нас > 28:
                continue
            v = (крупно[x, y] * 0.45 + мелко[x, y] * 0.55 - 78) / 108 * сила
            if L >= бел:
                новый = СВЕТЛО
            elif L >= сер:
                новый = тон(поле, v, x, y)
            elif L >= тень:
                новый = тон(врезка, v, x, y)
            elif L >= чернь:
                новый = ТЁМНО
            else:
                новый = КРАЙ
            px[x, y] = новый + (a,)
    return им


def оковать(им):
    """Стежки по краю и латунные скобы в углах — подпись лазарета.

    Без них перекрашенное окно остаётся просто тёмным: планшет осмотра
    узнаётся именно по шву и скобам. Рисуем по рамке самой панели
    (левый верхний угол холста, размер — по непрозрачной области),
    отступив внутрь на три пикселя: ванильные окна держат там поле,
    и ни один слот не задет.
    """
    рамка = им.getbbox()
    if рамка is None:
        return им
    _, _, ш, в = рамка
    if ш < 120 or в < 100:          # мелкие окна оковка только загромоздит
        return им
    px = им.load()
    for x in range(6, ш - 6, 4):
        for y in (3, в - 4):
            px[x, y] = _лз.ШОВ + (255,)
            px[x + 1, y] = _лз.ШОВ + (255,)
    for y in range(6, в - 6, 4):
        for x in (3, ш - 4):
            px[x, y] = _лз.ШОВ + (255,)
            px[x, y + 1] = _лз.ШОВ + (255,)
    for ух, уy, дx, дy in ((2, 2, 1, 1), (ш - 3, 2, -1, 1),
                           (2, в - 3, 1, -1), (ш - 3, в - 3, -1, -1)):
        for i in range(7):
            px[ух + дx * i, уy] = ЛАТУНЬ[1] + (255,)
            px[ух, уy + дy * i] = ЛАТУНЬ[1] + (255,)
        px[ух + дx, уy + дy] = ЛАТУНЬ[0] + (255,)
        px[ух + дx * 2, уy + дy * 2] = ЛАТУНЬ[3] + (255,)
    return им


def перекрасить_значок(им, гамма):
    """Значок HUD в одну гамму: силуэт ванильный, цвет наш."""
    им = им.convert("RGBA")
    px = им.load()
    for y in range(им.height):
        for x in range(им.width):
            r, g, b, a = px[x, y]
            if a == 0:
                continue
            L, _ = _ключ((r, g, b))
            # Ступень тем светлее, чем светлее был ванильный пиксель:
            # блик сердца остаётся бликом, обводка — обводкой.
            шаг = 0 if L >= 190 else 1 if L >= 130 else 2 if L >= 70 else 3
            px[x, y] = гамма[шаг] + (a,)
    return им


