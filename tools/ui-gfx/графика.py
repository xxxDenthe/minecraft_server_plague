    цель = ПАК / "assets/legendarytooltips/textures/gui/tooltip_borders.png"
    цель.parent.mkdir(parents=True, exist_ok=True)
    рамка.save(цель)
    показать.append(рамка.crop((0, 0, 64, 16)).resize((256, 64), Image.NEAREST))
    print("подсказки:\n  legendarytooltips/tooltip_borders.png")

    (ПАК / "pack.mcmeta").write_text(json.dumps({
        "pack": {"pack_format": 34,
                 "description": "Чума — окна в коже полевого лазарета"}
    }, ensure_ascii=False, indent=2), encoding="utf-8")

    # Иконка пака: кусок той же кожи со скобой — в списке ресурспаков
    # пак должен узнаваться с одного взгляда.
