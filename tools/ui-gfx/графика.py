def превью(куски):
    """Все окна рядом на нейтральном фоне — чтобы смотреть до игры."""
    ширина = 560
    полоса, x, y, высота_ряда = [], 0, 0, 0
    места = []
    for им in куски:
        if x + им.width > ширина and x:
            y += высота_ряда + 6
            x, высота_ряда = 0, 0
        места.append((им, x, y))
        x += им.width + 6
        высота_ряда = max(высота_ряда, им.height)
    лист = Image.new("RGBA", (ширина, y + высота_ряда + 6), (96, 96, 100, 255))
    for им, мx, мy in места:
        лист.alpha_composite(им, (мx, мy))
    return лист.resize((лист.width * 2, лист.height * 2), Image.NEAREST)


def main():
    if not ВАНИЛЬ.exists():
        raise SystemExit(f"не найден ванильный клиент: {ВАНИЛЬ}")
    ПАК.mkdir(parents=True, exist_ok=True)
    показать = []

    with zipfile.ZipFile(ВАНИЛЬ) as jar:
        print("окна:")
        for имя in ОКНА + ТВОРЧЕСКИЙ:
            им = перекрасить(из_ванили(jar, f"container/{имя}.png"), zlib.crc32(имя.encode()))
            # Творческие вкладки оковку не получают: их bbox включает
            # ряд вкладок сверху, и шов лёг бы поперёк них.
            if not имя.startswith("creative_inventory/"):
                оковать(им)
            положить(им, f"container/{имя}.png")
            print(f"  {имя}")
            if имя in ("crafting_table", "generic_54", "inventory", "furnace"):
                показать.append(им.crop(им.getbbox()))

        print("большие кнопки:")
        for имя, (поле, обводка) in КНОПКИ.items():
            им = перекрасить_кнопку(из_ванили(jar, f"sprites/{имя}.png"),
                                    zlib.crc32(имя.encode()), поле, обводка)
