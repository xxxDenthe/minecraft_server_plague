# ── шрифт ───────────────────────────────────────────────────────────
#
# Начертание лазарета уже есть в моде: им набран заголовок экрана
# здоровья. Пак не рисует его заново и не переписывает описание руками,
# а читает `plaguecore/.../font/lazaret.json`, забирает оттуда лист
# и подставляет тот же набор знаков ванильному шрифту
# `minecraft:default`. Подкрутили начертание в моде — поехало и
# в интерфейсе, потому что источник один.
#
# Порядок поставщиков важен: кто раньше, тот и рисует знак. Наш лист
# идёт до `minecraft:include/default`, поэтому русские буквы и цифры
# берутся из него, а латиница и всё прочее падают в ваниль. Это и есть
# та раскладка, по которой шрифт уже работает в моде.
#
# Начертаний в листе два: прописные и настоящие строчные ростом
# в пять пикселей. Пока шрифт жил в моде, строчных не было вовсе —
# ячейки несли картинку прописных, и заголовку из двух слов это
# годилось. Раздали шрифт всему интерфейсу — текст пошёл заглавными,
# и строчные пришлось нарисовать. Вернуть ванильный — выключить пак.


def одеть_шрифт():
    опис = json.loads(ШРИФТ_ЛАЗАРЕТА.read_text(encoding="utf-8"))
    поставщики = [п for п in опис["providers"] if п.get("type") != "reference"]
    if not поставщики:
        print("  в шрифте мода нет своего листа — пропускаю")
        return
    # Лист копируется в пак, а не берётся ссылкой из мода. Ссылка была бы
    # короче, но пак уезжает игрокам сам по себе: не доедет джарник —
    # и шрифт останется без картинки. Расхождения копия не даёт, её
    # переписывает каждый запуск скрипта из того же единственного листа.
    for п in поставщики:
        прост, путь = п["file"].split(":")
        откуда = (ШРИФТ_ЛАЗАРЕТА.parents[1] / "textures" / путь)
        куда = ПАК / ("assets/lazaret/textures/" + путь)
