def _девятью(им, ш, в, поле):
    """Собрать спрайт на размер так же, как его соберёт игра.

    Углы несжимаемы, края и середина размножаются плитками. Нужно
    только для контрольного листа — в игре это делает сам Minecraft.
    """
    с = им.width
    сер = с - поле * 2
    вых = Image.new("RGBA", (ш, в), (0, 0, 0, 0))

    def плиткой(кус, дx, дy, дш, дв):
        for y in range(дy, дy + дв, кус.height):
            for x in range(дx, дx + дш, кус.width):
                вых.alpha_composite(
                    кус.crop((0, 0, min(кус.width, дx + дш - x),
                              min(кус.height, дy + дв - y))), (x, y))

    гx, гy = ш - поле, в - поле
    вых.alpha_composite(им.crop((0, 0, поле, поле)), (0, 0))
    вых.alpha_composite(им.crop((с - поле, 0, с, поле)), (гx, 0))
    вых.alpha_composite(им.crop((0, с - поле, поле, с)), (0, гy))
    вых.alpha_composite(им.crop((с - поле, с - поле, с, с)), (гx, гy))
    плиткой(им.crop((поле, 0, поле + сер, поле)), поле, 0, ш - поле * 2, поле)
    плиткой(им.crop((поле, с - поле, поле + сер, с)), поле, гy, ш - поле * 2, поле)
    плиткой(им.crop((0, поле, поле, поле + сер)), 0, поле, поле, в - поле * 2)
    плиткой(им.crop((с - поле, поле, с, поле + сер)), гx, поле, поле, в - поле * 2)
    плиткой(им.crop((поле, поле, поле + сер, поле + сер)),
            поле, поле, ш - поле * 2, в - поле * 2)
    return вых


def макет_jade(плашка, слот):
    """Как ляжет подсказка в игре — для контрольного листа.

    Настоящую выдать неоткуда: рисует её мод и только в игре. Зато
    размеры считаются по его же правилам — поле темы плюс значок с
    гнездом, — и высота выходит ровно та же, что у встроенной тёмной
    темы: 4 + 18 + 4 = 26 пикселей. Рядом для сверки положен и сам
    оригинал, рамкой в пиксель.
    """
    поле = тема_jade()["tooltipStyle"]["padding"][0]
    ш, в = 148, поле * 2 + СЛОТ
    мир = Image.new("RGBA", (ш * 2 + 8, в), (74, 82, 64, 255))

    # слева — оригинал: заливка и рамка в пиксель, как рисует Jade сам
    ориг = Image.new("RGBA", (ш, в), (19, 19, 19, 179))
    px = ориг.load()
    for x in range(ш):
        px[x, 0] = px[x, в - 1] = (56, 56, 56, 255)
    for y in range(в):
        px[0, y] = px[ш - 1, y] = (56, 56, 56, 255)
    мир.alpha_composite(ориг)

    наш = _девятью(плашка, ш, в, НАРЕЗКА)
    наш.alpha_composite(слот, (поле, поле))
    мир.alpha_composite(наш, (ш + 8, 0))

    for x0 in (0, ш + 8):
        мир.alpha_composite(Image.new("RGBA", (74, 5), КОСТЬ + (255,)),
                            (x0 + поле + СЛОТ + 4, поле + 2))
        мир.alpha_composite(Image.new("RGBA", (52, 5), _лз.КОСТЬ_Т + (255,)),
                            (x0 + поле + СЛОТ + 4, поле + 11))
    return мир


