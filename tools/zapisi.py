# ── Вёрстка: абзацы раскладываются по листам книги ─────────────────
# Экран книги режет строку по 114 пикселям, а кириллица в ванильном
# шрифте почти вся по шесть пикселей на букву. Девятнадцать знаков в
# строке — честная оценка; лист держим в одиннадцать строк, а не в
# четырнадцать возможных, чтобы у текста оставался воздух.

В_СТРОКЕ, НА_ЛИСТЕ = 19, 12

ЗГ, ПД = chr(1), chr(2)   # метки вёрстки: заголовок и подпись


def строк(абзац):
    абзац = абзац.lstrip(ЗГ + ПД)
    длина, строки = 0, 1
    for слово in абзац.split():
        n = len(слово)
        if длина and длина + 1 + n > В_СТРОКЕ:
            строки += 1
            длина = n
        else:
            длина += (1 if длина else 0) + n
    return строки


def листы(абзацы):
    """Разложить абзацы по листам, не разрывая абзац и не оставляя сирот.

    Жадная укладка «пока влезает» регулярно оставляет последним листом
    одну строку — на развороте это выглядит оборванным. Поэтому сперва
    считаем, сколько листов выйдет всё равно, и раскладываем ровно.
    """
    длины = [строк(а) for а in абзацы]
    всего = sum(длины) + len(длины) - 1
    сколько = max(1, -(-всего // НА_ЛИСТЕ))
    предел = max(max(длины), -(-всего // сколько))

    вышло, текущий, занято = [], [], 0
    for абзац, н in zip(абзацы, длины):
        добавка = н + (1 if текущий else 0)
        if текущий and занято + добавка > предел:
            вышло.append(текущий)
            текущий, занято = [], 0
            добавка = н
        текущий.append(абзац)
        занято += добавка
    if текущий:
        вышло.append(текущий)
    return ["\n\n".join(л) for л in вышло]


# ── Выдача датапаком ───────────────────────────────────────────────

def снбт_строка(текст):
    """Строка SNBT в двойных кавычках."""
    return '"%s"' % текст.replace("\\", "\\\\").replace('"', '\\"')


def снбт_лист(часть):
    """Лист книги: JSON-компонент внутри строки SNBT.

    Перевод строки проходит два разбора — сначала SNBT, потом JSON, —
    поэтому обратный слэш из json.dumps удваивается: SNBT отдаёт JSON-у
    два знака, а уже он делает из них перенос.
    """
    j = json.dumps(часть, ensure_ascii=False)
    return "'%s'" % j.replace("\\", "\\\\").replace("'", "\\'")


# Заголовок и подпись — не украшение, а признак архивного документа:
# бумага управы начинается с того, чья она, и кончается тем, чья рука.
# Черта под заголовком набрана длинными тире: они есть в ванильном
# шрифте, а знаки псевдографики в нём не все, и вместо черты вышли бы
# квадратики.
ЧЕРТА = "—" * 11


def страница(тело):
    части = []
    куски = тело.split("\n\n")
    for н, кусок in enumerate(куски):
        конец = "\n\n" if н < len(куски) - 1 else ""
        if кусок.startswith(ЗГ):
            заг, черта = кусок[1:].split("\n")
            части.append({"text": заг + "\n", "bold": True})
            части.append({"text": черта + конец, "color": "#6a5c49"})
        elif кусок.startswith(ПД):
            части.append({"text": кусок[1:] + конец,
                          "italic": True, "color": "#6a5c49"})
        else:
            части.append({"text": кусок + конец})
    return {"text": "", "extra": части}


def дать(заголовок, автор, вид, абзацы):
    # Заголовок и подпись идут в вёрстку обычными абзацами: иначе она
    # их не считает, и первый лист переполняется ровно на три строки.
    рамка = [ЗГ + заголовок + "\n" + ЧЕРТА] + list(абзацы) + [ПД + автор]
    страницы = ",".join(снбт_лист(страница(л)) for л in листы(рамка))
    начинка = "{title:%s,author:%s,pages:[%s]}" % (
        снбт_строка(заголовок), снбт_строка(автор), страницы)
    return ("give @s plaguecore:archive_record["
            "minecraft:custom_model_data=%d,minecraft:written_book_content=%s]"
            % (вид, начинка))


