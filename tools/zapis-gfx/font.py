# -*- coding: utf-8 -*-
"""Рунический алфавит тайнописи: 33 глифа, собранные из штрихов."""
from PIL import Image
import random

W, H = 6, 7          # рабочее поле глифа внутри ячейки 8x8
CELL = 8

def пусто():
    return [[0]*W for _ in range(H)]

def стержень(g, c=1):
    for y in range(1, 7): g[y][c] = 255

# набор ветвей: каждая — функция, дорисовывающая штрих к стержню
def верх_диаг(g):   # из стержня вверх-вправо
    for i in range(3): g[3-i][2+i] = 255
def низ_диаг(g):
    for i in range(3): g[3+i][2+i] = 255
def верх_вниз(g):   # из верхушки вниз-вправо
    for i in range(3): g[1+i][2+i] = 255
def низ_вверх(g):
    for i in range(3): g[6-i][2+i] = 255
def верх_бар(g):
    for x in range(2, 5): g[1][x] = 255
def сред_бар(g):
    for x in range(2, 5): g[3][x] = 255
def ниж_бар(g):
    for x in range(2, 5): g[6][x] = 255
def правый_стержень(g):
    for y in range(1, 7): g[y][4] = 255
def полустержень_верх(g):
    for y in range(1, 4): g[y][4] = 255
def полустержень_низ(g):
    for y in range(4, 7): g[y][4] = 255
def точка_верх(g):
    g[1][4] = 255
def точка_низ(g):
    g[6][4] = 255
def крюк_верх(g):
    g[1][2] = 255; g[1][3] = 255; g[2][3] = 255
def крюк_низ(g):
    g[6][2] = 255; g[6][3] = 255; g[5][3] = 255
def клин(g):
    g[2][2] = 255; g[3][3] = 255; g[4][2] = 255
def хвост(g):        # стержень уходит влево внизу
    g[6][0] = 255; g[5][0] = 255

ВЕТВИ = [верх_диаг, низ_диаг, верх_вниз, низ_вверх, верх_бар, сред_бар,
         ниж_бар, правый_стержень, полустержень_верх, полустержень_низ,
         точка_верх, точка_низ, крюк_верх, крюк_низ, клин, хвост]

АЛФАВИТ = "абвгдежзийклмнопрстуфхцчшщъыьэюя"  # 32, ё добавим как я+точка

def зеркало(g):
    return [list(reversed(r)) for r in g]

БЕЗ_СТЕРЖНЯ = [
    # две диагонали, без вертикали — «гласные» этого письма
    ["..#...", ".#.#..", "#...#.", "#...#.", "#...#.", ".#.#..", "..#..."],
    ["#...#.", ".#.#..", "..#...", "..#...", ".#.#..", "#...#.", "......"],
    ["#....#", ".#..#.", "..##..", "..##..", ".#..#.", "#....#", "......"],
    ["..#...", ".###..", "#.#.#.", "..#...", "..#...", "..#...", "......"],
    ["......", "#####.", "....#.", "...#..", "..#...", "#####.", "......"],
    ["..#...", "..#...", "#####.", "..#...", "..#...", "..#...", "......"],
]

def собрать():
    """Три семьи знаков вперемешку: со стержнем слева, зеркальные, без стержня."""
    основа, видели = [], set()
    for i in range(len(ВЕТВИ)):
        for j in range(i, len(ВЕТВИ)):
            g = пусто()
            стержень(g)
            ВЕТВИ[i](g)
            if j != i: ВЕТВИ[j](g)
            к = tuple(tuple(r) for r in g)
            if к in видели: continue
            видели.add(к)
            основа.append(g)
    прямые = основа[:]
    зеркальные = [зеркало(g) for g in основа[3:]]
    прочие = [[[255 if c == "#" else 0 for c in ряд] for ряд in форма]
              for форма in БЕЗ_СТЕРЖНЯ]
    # чередуем семьи, чтобы соседние буквы не выглядели роднёй
    смесь, к = [], [прямые, зеркальные, прочие]
    и = [0, 0, 0]
    н = 0
    while len(смесь) < 33:
        сем = н % 3
        if и[сем] < len(к[сем]):
            смесь.append(к[сем][и[сем]]); и[сем] += 1
        н += 1
        if all(и[x] >= len(к[x]) for x in range(3)): break
    return смесь

def рука(g, семя):
    """Рукописная неровность: концы штрихов выцветают, пара пикселей бледнее."""
    rnd = random.Random(семя)
    точки = [(y, x) for y in range(H) for x in range(W) if g[y][x]]
    for _ in range(2):
        if not точки: break
        y, x = rnd.choice(точки)
        g[y][x] = 170
    # лёгкий нажим на кончике
    for y, x in list(точки):
        соседи = sum(1 for dy, dx in ((1,0),(-1,0),(0,1),(0,-1))
                     if 0 <= y+dy < H and 0 <= x+dx < W and g[y+dy][x+dx])
        if соседи == 1 and rnd.random() < 0.45:
            ny, nx = y + rnd.choice([-1, 1]), x + rnd.choice([-1, 1])
            if 0 <= ny < H and 0 <= nx < W and not g[ny][nx]:
                g[ny][nx] = 140
    return g

def лист():
    глифы = собрать()[:33]
    for н, g in enumerate(глифы): рука(g, н * 7919)
    im = Image.new("RGBA", (128, 48), (255, 255, 255, 0))
    px = im.load()
    порядок = list(АЛФАВИТ) + ["ё"]
    # три ряда строчных, три ряда заглавных — картинка одна и та же
    места = {}
    for н, ch in enumerate(порядок):
        места[ch] = глифы[н % 33]
    def влож(cx, cy, g):
        for y in range(H):
            for x in range(W):
                a = g[y][x]
                if a: px[cx*CELL + x + 1, cy*CELL + y] = (255, 255, 255, a)
    строки = []
    for ряд in range(2):
        строки.append(порядок[ряд*16:(ряд+1)*16])
    строки.append(порядок[32:])
    все = строки + [[c.upper() for c in s] for s in строки]
    for cy, строка in enumerate(все):
        for cx, ch in enumerate(строка):
            влож(cx, cy, места[ch.lower()])
    return im, все

