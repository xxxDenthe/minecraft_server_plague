# -*- coding: utf-8 -*-
"""Три записи в руке. Палитра приглушённая, без бликов и светлых контуров."""
from PIL import Image

C = {
    "p": (203, 193, 170), "q": (186, 174, 149), "r": (163, 150, 125),
    "i": (86,  74,  60), "k": (46,  38,  30), "l": (112, 98, 78),
    "t": (128, 106,  76), "u": (94,  76,  54),
    "c": (74,  54,  44), "d": (52,  37,  31), "e": (98,  74,  62),
    "g": (92,  92,  74), "h": (68,  68,  55), "j": (114, 112,  90),
    "m": (80,  66,  46), "n": (124, 100,  64),
}

class Холст:
    def __init__(s): s.px = {}
    def т(s, x, y, c):
        if 0 <= x < 16 and 0 <= y < 16: s.px[(x, y)] = C[c]
    def прям(s, x0, y0, x1, y1, c):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1): s.т(x, y, c)
    def гор(s, x0, x1, y, c):
        for x in range(x0, x1 + 1): s.т(x, y, c)
    def вер(s, x, y0, y1, c):
        for y in range(y0, y1 + 1): s.т(x, y, c)
    def обвод(s, x0, y0, x1, y1, c="k"):
        s.гор(x0, x1, y0, c); s.гор(x0, x1, y1, c)
        s.вер(x0, y0, y1, c); s.вер(x1, y0, y1, c)
    def образ(s):
        im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
        px = im.load()
        for (x, y), c in s.px.items(): px[x, y] = c + (255,)
        return im

def бумаги():
    """Пачка листов управы, перехваченная бечёвкой. Скучный документ."""
    h = Холст()
    h.прям(7, 2, 14, 5, "q"); h.обвод(6, 1, 14, 5)      # лист сзади, наискось
    h.прям(3, 4, 12, 13, "p"); h.обвод(2, 3, 13, 14)    # верхний лист
    # писарская рука: короткие слова, а не линейки; чернила выцвели
    for y, куски in ((5,  ((4, 5), (7, 9))),
                     (7,  ((4, 6), (10, 11))),
                     (9,  ((4, 4), (6, 7), (10, 12))),
                     (11, ((4, 6), (10, 11))),
                     (13, ((4, 5), (7, 8)))):
        for x0, x1 in куски:
            h.гор(x0, x1, y, "l")
    h.гор(4, 6, 5, "i"); h.т(4, 9, "i"); h.гор(10, 11, 11, "i")
    h.вер(7, 4, 13, "u"); h.вер(8, 4, 13, "t")          # бечёвка поперёк
    h.прям(6, 8, 9, 9, "u"); h.т(6, 8, "t"); h.т(9, 9, "t")   # узел
    h.гор(3, 12, 14, "r")                               # тень нижнего края
    h.т(13, 5, "r"); h.т(13, 4, "r")
    return h.образ()

def тетрадь():
    """Церковная тетрадь: тёмный переплёт, торец блока, вытертый крест."""
    h = Холст()
    h.прям(12, 3, 13, 12, "p"); h.вер(13, 4, 11, "q")   # торец страниц
    h.обвод(11, 2, 14, 13)
    h.прям(4, 2, 11, 13, "c"); h.обвод(3, 1, 12, 14)    # крышка
    h.вер(4, 2, 13, "d"); h.вер(5, 2, 13, "d")          # корешок
    for y in (4, 7, 10): h.т(4, y, "e"); h.т(4, y + 1, "e")   # стежки
    h.вер(8, 4, 9, "e"); h.гор(7, 9, 6, "e")            # крест, тонкий
    h.т(8, 5, "d"); h.т(9, 6, "c")                      # вытерт неровно
    h.прям(6, 11, 10, 12, "d")                          # потёртость низа
    h.гор(4, 11, 13, "d")
    return h.образ()

def журнал():
    """Журнал дренажа: холщовая обложка, торчащие листы, земля по углам."""
    h = Холст()
    for y, x1 in ((3, 13), (4, 14), (5, 13), (6, 14), (7, 13),
                  (8, 14), (9, 13), (10, 14), (11, 13)):
        h.гор(12, x1, y, "p" if y % 2 else "q")          # листы лежат неровно
        h.т(x1, y, "r")
    h.прям(3, 2, 12, 13, "g"); h.обвод(2, 1, 12, 14)    # обложка
    h.вер(3, 2, 13, "h"); h.вер(4, 2, 13, "h")          # корешок
    for x, y in ((6, 3), (9, 4), (5, 6), (11, 7), (7, 9),
                 (10, 11), (4, 12), (8, 12)): h.т(x, y, "j")   # плетение холста
    h.гор(3, 12, 7, "u"); h.гор(3, 12, 8, "t")          # завязка поперёк
    h.т(6, 7, "t"); h.т(9, 8, "u")
    h.прям(4, 11, 7, 13, "m"); h.т(5, 12, "n"); h.т(6, 13, "m")  # земля
    h.т(11, 2, "h"); h.т(12, 2, "k"); h.т(12, 3, "h")   # разбитый угол
    h.гор(4, 11, 14, "h")
    return h.образ()

ВСЕ = {"zapis_papers": бумаги, "zapis_chapel": тетрадь, "zapis_ledger": журнал}

