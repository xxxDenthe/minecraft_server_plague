# -*- coding: utf-8 -*-
"""Разворот записи: старая бумага вместо ванильной книжки в красном переплёте.

Геометрия та же, что у minecraft:textures/gui/book.png — экран книги
блитит область 192x192 и кладёт текст в x 36..150, y 30..158, а номер
листа прижимает вправо к x=148, y=16. Поэтому бумага обязана накрывать
эти прямоугольники с полями.
"""
from PIL import Image
import random

БУМАГА = [(192, 182, 159), (184, 173, 150), (175, 163, 139), (164, 151, 127)]
КРАЙ   = [(152, 139, 115), (132, 119,  97), (110,  97,  78)]
ШОВ    = [(74, 62, 50), (58, 47, 38), (44, 35, 28)]
НИТЬ   = (146, 128, 102)
РУЛЬ   = (150, 132, 112)   # разлиновка: чуть темнее бумаги, не линия — след

ЛЕВО, ПРАВО = 22, 164      # переплёт 22..28, лист 29..164
ВЕРХ, НИЗ   = 4, 176

def шум(rnd, x, y):
    """Крап бумаги: три тона вперемешку, без плавных переходов."""
    v = rnd.random()
    if v < 0.06: return БУМАГА[3]
    if v < 0.24: return БУМАГА[2]
    if v < 0.62: return БУМАГА[1]
    return БУМАГА[0]

def пятно(px, rnd, cx, cy, r):
    """Затёк: неровное пятно на тон темнее, без ореола."""
    for y in range(cy - r, cy + r + 1):
        for x in range(cx - r, cx + r + 1):
            if not (ЛЕВО <= x <= ПРАВО and ВЕРХ <= y <= НИЗ): continue
            d = ((x - cx) ** 2 + (y - cy) ** 2) ** 0.5 + rnd.uniform(-1.1, 1.1)
            if d > r: continue
            c = px[x, y]
            k = 0.88 if d > r * 0.6 else 0.8
            px[x, y] = (int(c[0]*k), int(c[1]*k), int(c[2]*k), 255)

def лист():
    rnd = random.Random(20260912)
    im = Image.new("RGBA", (256, 256), (0, 0, 0, 0))
    px = im.load()

    # рваный правый и нижний край: у листа он не по линейке
    выступ = {y: rnd.choice([0, 0, 0, -1, -1, 1]) for y in range(ВЕРХ, НИЗ + 1)}
    донизу = {x: rnd.choice([0, 0, 0, -1, 1]) for x in range(ЛЕВО, ПРАВО + 2)}

    # тон бумаги: мягкое поле пятен, разложенное по четырём тонам
    # упорядоченным дизерингом — плавных переходов на выходе не остаётся.
    поле = Image.new("L", (32, 32))
    поле.putdata([rnd.randrange(60, 196) for _ in range(32 * 32)])
    поле = поле.resize((256, 256), Image.BICUBIC)
    мелко = Image.new("L", (64, 64))
    мелко.putdata([rnd.randrange(90, 166) for _ in range(64 * 64)])
    мелко = мелко.resize((256, 256), Image.BICUBIC)
    поле, мелко = поле.load(), мелко.load()
    БАЙЕР = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]

    for y in range(ВЕРХ, НИЗ + 1):
        пр = ПРАВО + выступ[y]
        for x in range(ЛЕВО, пр + 1):
            ни = НИЗ + донизу.get(x, 0)
            if y > ни: continue
            v = поле[x, y] * 0.45 + мелко[x, y] * 0.55
            v = (v - 70) / 110 * 3.0 + (БАЙЕР[y % 4][x % 4] - 7.5) / 9.0
            т = min(3, max(0, int(round(v))))
            px[x, y] = БУМАГА[т] + (255,)

    # переплёт слева: тёмная полоса и стежки
    for y in range(ВЕРХ, НИЗ + 1):
        ни = НИЗ + донизу.get(ЛЕВО, 0)
        if y > ни: continue
        for x in range(ЛЕВО, ЛЕВО + 7):
            т = ШОВ[1] if x in (ЛЕВО, ЛЕВО + 6) else ШОВ[0]
            if rnd.random() < 0.18: т = ШОВ[2]
            px[x, y] = т + (255,)
    for y in range(ВЕРХ + 9, НИЗ - 6, 21):          # стежки нити
        for dy in (0, 1):
            for x in range(ЛЕВО + 2, ЛЕВО + 5):
                px[x, y + dy] = НИТЬ + (255,)
        px[ЛЕВО + 7, y] = (ЛЕВО and НИТЬ) + (255,)

    # потемневшие поля: два шага, без градиента
    for y in range(ВЕРХ, НИЗ + 1):
        пр = ПРАВО + выступ[y]
        for x in range(ЛЕВО + 7, пр + 1):
            ни = НИЗ + донизу.get(x, 0)
            if y > ни: continue
            до_края = min(x - (ЛЕВО + 7), пр - x, y - ВЕРХ, ни - y)
            if до_края > 6: continue
            c = px[x, y]
            шаг = 0 if до_края <= 1 else (1 if до_края <= 3 else 2)
            цель = КРАЙ[2 - шаг]
            k = 0.72 if шаг == 0 else (0.46 if шаг == 1 else 0.24)
            if rnd.random() < 0.12: k += 0.15     # кромка неровная
            px[x, y] = tuple(int(c[i]*(1-k) + цель[i]*k) for i in range(3)) + (255,)

    # разлиновка: чем писарь держал строку. Экран кладёт строки
    # в y 30..158 с шагом 9 — след идёт под каждой.
    for л in range(14):
        y = 30 + л * 9 + 8
        for x in range(34, 151):
            if rnd.random() < 0.22: continue        # след не сплошной
            c = px[x, y]
            if c[3] == 0: continue
            px[x, y] = tuple(int(c[i]*0.68 + РУЛЬ[i]*0.32) for i in range(3)) + (255,)
    for y in range(24, 164):                        # поле, отчёркнутое слева
        c = px[33, y]
        if c[3] and rnd.random() > 0.18:
            px[33, y] = tuple(int(c[i]*0.7 + (138, 104, 88)[i]*0.3) for i in range(3)) + (255,)

    # следы времени
    пятно(px, rnd, 150, 168, 7)
    пятно(px, rnd,  46,  22, 5)
    пятно(px, rnd, 120,  96, 4)
    пятно(px, rnd, 158,  60, 3)

    # заломленный уголок внизу справа
    for i in range(11):
        for j in range(11 - i):
            x, y = ПРАВО - i, НИЗ - j
            if i + j < 6:
                px[x, y] = (0, 0, 0, 0)
            elif i + j < 8:
                px[x, y] = КРАЙ[1] + (255,)
    return im

def стрелка(вперёд, ярче):
    """Навигация — не кнопка, а чернильная галочка на поле листа."""
    im = Image.new("RGBA", (23, 13), (0, 0, 0, 0))
    px = im.load()
    ink = (58, 47, 38, 255) if ярче else (96, 84, 68, 235)
    сл = (58, 47, 38, 140) if ярче else (96, 84, 68, 110)
    для = [(0, 0), (1, 1), (2, 2), (3, 3), (2, 4), (1, 5), (0, 6)]
    ox, oy = 9, 3
    for dx, dy in для:
        x = ox + (dx if вперёд else 3 - dx)
        px[x, oy + dy] = ink
        if 0 <= x + (1 if вперёд else -1) < 23:
            px[x + (1 if вперёд else -1), oy + dy] = сл
    return im
