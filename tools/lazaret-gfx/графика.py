def шрифт():
    """Лист 128×48: 16 × 6 ячеек по 8×8, знак занимает 7 верхних строк."""
    rnd = random.Random(0x1A2E7)
    им = Image.new("RGBA", (128, 48), (0, 0, 0, 0))
    px = им.load()
    for ряд, строка in enumerate(РЯДЫ):
        for кол, знак in enumerate(строка):
            рис = ЗНАКИ.get(знак.upper())
            if рис is None:
                continue
            for дy, линия in enumerate(рис):
                for дx, точка in enumerate(линия):
                    if точка != "#":
                        continue
                    # часть пикселей выцвела: знаки выглядят вытравленными,
                    # а не набранными. Ровно тот же приём, что у тайнописи.
