БАЙЕР = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]


def поле_шума(rnd, размер, мелко, низ, верх):
    """Мягкое поле 0..255, растянутое до размера панели."""
    им = Image.new("L", (мелко, мелко))
    им.putdata([rnd.randrange(низ, верх) for _ in range(мелко * мелко)])
    return им.resize(размер, Image.BICUBIC).load()


def тон(палитра, v, x, y):
    """Значение 0..3 с дизерингом — плавных переходов на выходе нет."""
    v = v + (БАЙЕР[y % 4][x % 4] - 7.5) / 9.0
    return палитра[min(3, max(0, int(round(v))))]


# ── панель ──────────────────────────────────────────────────────────

def врезка(px, x, y, ш, в, палитра, крупно, мелко):
    """Утопленное окно: тёмный край сверху-слева, светлый снизу-справа."""
    for yy in range(y, y + в):
        for xx in range(x, x + ш):
            v = (крупно[xx, yy] * 0.5 + мелко[xx, yy] * 0.5 - 90) / 105 * 3.0
            px[xx, yy] = тон(палитра, v, xx, yy) + (255,)
    for xx in range(x, x + ш):
        px[xx, y] = ТЁМНО + (255,)
        px[xx, y + в - 1] = СВЕТЛО + (255,)
    for yy in range(y, y + в):
        px[x, yy] = ТЁМНО + (255,)
        px[x + ш - 1, yy] = СВЕТЛО + (255,)
    px[x, y + в - 1] = ТЁМНО + (255,)
    px[x + ш - 1, y] = ТЁМНО + (255,)


def уголок(px, x, y, знакX, знакY):
    """Латунный уголок-скоба с заклёпкой. знакX/Y = ±1, куда смотрит."""
    д = 13
    for i in range(д):
        for t in range(3):
            гx, гy = x + знакX * i, y + знакY * t
            px[гx, гy] = ЛАТУНЬ[0 if t == 0 else (1 if t == 1 else 2)] + (255,)
            гx, гy = x + знакX * t, y + знакY * i
            px[гx, гy] = ЛАТУНЬ[0 if t == 0 else (1 if t == 1 else 2)] + (255,)
    # заклёпка на сгибе: светлая точка, тёмный низ — объём без градиента
    зx, зy = x + знакX * 6, y + знакY * 1
    px[зx, зy] = ЛАТУНЬ[0] + (255,)
    px[зx, зy + знакY] = ЛАТУНЬ[3] + (255,)
    зx, зy = x + знакX * 1, y + знакY * 6
    px[зx, зy] = ЛАТУНЬ[0] + (255,)
    px[зx + знакX, зy] = ЛАТУНЬ[3] + (255,)


def панель():
    rnd = random.Random(20260916)
    им = Image.new("RGBA", (256, 256), (0, 0, 0, 0))
    px = им.load()

    крупно = поле_шума(rnd, (256, 256), 24, 60, 196)
    мелко = поле_шума(rnd, (256, 256), 72, 92, 164)

    # кожаное поле: шапка своим тоном, остальное — телом панели
    for y in range(В):
        палитра = ПОЛОСА if y < ШАПКА else КОЖА
        for x in range(Ш):
            v = (крупно[x, y] * 0.45 + мелко[x, y] * 0.55 - 78) / 108 * 3.0
            px[x, y] = тон(палитра, v, x, y) + (255,)

    # потёртости: редкие тёмные царапины вдоль волокна
    for _ in range(46):
        цx, цy = rnd.randrange(4, Ш - 8), rnd.randrange(4, В - 4)
        длина = rnd.randrange(3, 11)
        for i in range(длина):
            x = цx + i
            y = цy + (0 if rnd.random() < 0.8 else rnd.choice((-1, 1)))
            if 0 <= x < Ш and 0 <= y < В:
                c = px[x, y]
                px[x, y] = (int(c[0] * .78), int(c[1] * .78), int(c[2] * .78), 255)

    # тёмный обрез по периметру и светлая фаска внутри него
    for x in range(Ш):
        px[x, 0] = px[x, В - 1] = КРАЙ + (255,)
        px[x, 1] = px[x, В - 2] = ТЁМНО + (255,)
    for y in range(В):
        px[0, y] = px[Ш - 1, y] = КРАЙ + (255,)
        px[1, y] = px[Ш - 2, y] = ТЁМНО + (255,)

    # строчка по краю: не линия, а стежки
    for x in range(6, Ш - 6, 4):
        for y in (4, В - 5):
            px[x, y] = ШОВ + (255,)
            px[x + 1, y] = ШОВ + (255,)
    for y in range(6, В - 6, 4):
        for x in (4, Ш - 5):
            px[x, y] = ШОВ + (255,)
            px[x, y + 1] = ШОВ + (255,)

    # разделитель под шапкой: тёмная линия и светлый отблеск под ней
    for x in range(3, Ш - 3):
        px[x, ШАПКА - 2] = ТЁМНО + (255,)
        px[x, ШАПКА - 1] = КРАЙ + (255,)
        px[x, ШАПКА] = СВЕТЛО + (255,)
    # латунь в разделителе на всю ширину: черта, обрывающаяся посреди
    # заголовка, читается как случайность, а не как линейка
    for x in range(8, Ш - 8):
        px[x, ШАПКА - 1] = ЛАТУНЬ[1] + (255,)
        px[x, ШАПКА - 2] = ЛАТУНЬ[2] + (255,)

    врезка(px, ОКНО_X, ОКНО_Y, ОКНО_Ш, ОКНО_В, ОКНО_Т, крупно, мелко)
    врезка(px, ПОЛЕ_X, ПОЛЕ_Y, ПОЛЕ_Ш, ПОЛЕ_В, КОЖА, крупно, мелко)

    # латунные засечки по углам врезок: обе привязаны к той же латуни,
    # что и уголки планшета, иначе окна выглядят вырезанными чужой рукой
    for ох, оy, ош, ов in ((ОКНО_X, ОКНО_Y, ОКНО_Ш, ОКНО_В),
                           (ПОЛЕ_X, ПОЛЕ_Y, ПОЛЕ_Ш, ПОЛЕ_В)):
        for зx, зy, шx, шy in ((ох, оy, 1, 1), (ох + ош - 1, оy, -1, 1),
                               (ох, оy + ов - 1, 1, -1), (ох + ош - 1, оy + ов - 1, -1, -1)):
            for i in range(4):
                px[зx + шx * i, зy] = ЛАТУНЬ[1] + (255,)
                px[зx, зy + шy * i] = ЛАТУНЬ[1] + (255,)

    уголок(px, 3, 3, 1, 1)
    уголок(px, Ш - 4, 3, -1, 1)
    уголок(px, 3, В - 4, 1, -1)
    уголок(px, Ш - 4, В - 4, -1, -1)
    return им


# ── рамка окошек на игровом экране ──────────────────────────────────
#
# Отдельный лист 48 × 48: из него собираются панельки Летописца поверх
# игры (летопись и снимок). Девять кусков — четыре угла, четыре края
# и середина; края и середина размножаются плиткой, а не растягиваются:
# растянутая кожа расчёсывается в полосы, и от пиксельной графики
# проекта ничего не остаётся.
#
# Лист свой, а не угол health_panel.png, хотя место там было: панели
# Летописца живут в lmpc_classes, а health_panel.png — в plaguecore,
# и два мода правятся из разных сессий. Разошедшийся PNG не слить
# руками, а лишний килобайт текстуры ничего не стоит.
#
# Раскладку читает lmpc_classes/client/LazaretHud.java — двигать нельзя.

ПЛАНКА_Ш = 48
ПЛАНКА_УГОЛ = 16


def планка():
    rnd = random.Random(20260917)
    с = ПЛАНКА_Ш
    им = Image.new("RGBA", (с, с), (0, 0, 0, 0))
    px = им.load()
    крупно = поле_шума(rnd, (с, с), 12, 60, 196)
    мелко = поле_шума(rnd, (с, с), 24, 92, 164)
    x0 = y0 = 0

    for y in range(с):
        for x in range(с):
            гx, гy = x0 + x, y0 + y
            # Шум вдвое слабее, чем на большой панели: края и середина
            # размножаются плиткой, и любой заметный рисунок кожи начал
            # бы повторяться через каждые шестнадцать пикселей.
            v = (крупно[гx, гy] * 0.45 + мелко[гx, гy] * 0.55 - 78) / 108 * 1.4
            # Чуть темнее панели осмотра: окошко лежит поверх игры,
            # и под ним должен читаться мир, а не только кожа.
            px[гx, гy] = тон(КОЖА, v + 0.4, гx, гy) + (232,)

    # Кайма и латунная черта идут по всем трём сегментам каждой стороны,
    # иначе на стыке плиток линия рвётся.
    for i in range(с):
        for край, тон_края in ((0, КРАЙ), (1, ТЁМНО), (2, ЛАТУНЬ[2])):
            px[x0 + i, y0 + край] = тон_края + (255,)
            px[x0 + i, y0 + с - 1 - край] = тон_края + (255,)
            px[x0 + край, y0 + i] = тон_края + (255,)
            px[x0 + с - 1 - край, y0 + i] = тон_края + (255,)

    # Заклёпки — только в углах: в краевых плитках они бы повторились
    # через каждые шестнадцать пикселей и превратились в орнамент.
    for зx, зy in ((5, 5), (с - 6, 5), (5, с - 6), (с - 6, с - 6)):
        px[x0 + зx, y0 + зy] = ЛАТУНЬ[0] + (255,)
        px[x0 + зx, y0 + зy + 1] = ЛАТУНЬ[3] + (255,)
    return им


