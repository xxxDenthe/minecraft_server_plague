def объём(px, x0, y0, узор, свет, тень):
    """
    Фигура светлая, а по нижней и правой кромке идёт тёмная кайма:
    свет падает сверху-слева. Тень ложится ровно на край силуэта,
    внутренние просветы остаются просветами.

    Прежний способ — копия узора со сдвигом на пиксель вниз — заливал
    тенью каждую дырку внутри силуэта, и значки выглядели рваными.
    """
    h, w = len(узор), len(узор[0])

    def занят(x, y):
        return 0 <= x < w and 0 <= y < h and узор[y][x] == "#"

    for dy in range(h):
        for dx in range(w):
            if узор[dy][dx] != "#":
                continue
            край = not занят(dx, dy + 1) or not занят(dx + 1, dy)
            px[x0 + dx, y0 + dy] = тень if край else свет


def значок(px, индекс, узор):
    """Значок вкладки: рисунок 10 × 10 с полем в пиксель внутри ячейки."""
    объём(px, индекс * ЯЧЕЙКА + 1, 1, узор, СВЕТ, ТЕНЬ)


def собрать():
    im = Image.new("RGBA", ЛИСТ, ПУСТО)
    px = im.load()

    значок(px, 0, САМОЧУВСТВИЕ)
    значок(px, 1, ТЕЛО)
    значок(px, 2, ОЩУЩЕНИЯ)
    значок(px, 3, ПАМЯТЬ)

    объём(px, 48, 0, КАПЛЯ, ВОДА, ВОДА_ТЕНЬ)

    return im


