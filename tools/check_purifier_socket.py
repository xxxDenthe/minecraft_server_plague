"""Гнездо вала у очистителей должно оставаться открытым.

Модель очистителя переживает переделки облика (форма A, латунный тир,
порты на ассетах Create), и каждый раз есть шанс заново заложить дыру
под вал сплошным кубом. Тогда вал из PurifierRenderer уедет внутрь
геометрии, и снизу опять будет глухое дно.

Запуск: python tools/check_purifier_socket.py
"""
import json
import os
import sys

БАЗА = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                    'lmpc_classes/src/main/resources/assets/lmpc_classes/models/block')

# Дыра в текстуре gearbox/brass_gearbox — ровно 6x6 пикселей.
ГНЕЗДО = (5, 11)
# Огрызок вала: translate(-1/16) + scale(0.30) в PurifierRenderer.
ВАЛ_НИЗ, ВАЛ_ВЕРХ = -1.0, -1.0 + 0.30 * 16


def кубы(модель):
    d = json.load(open(os.path.join(БАЗА, модель + '.json'), encoding='utf-8'))
    return [(e.get('name', '?'), e['from'], e['to']) for e in d['elements']]


def пересекаются(a, b):
    return all(a[0][i] < b[1][i] and b[0][i] < a[1][i] for i in range(3))


def проверить(модель):
    список = кубы(модель)

    # 1. Столб гнезда пуст от дна блока до потолка гнезда.
    д, п = ГНЕЗДО
    столб = ([д, 0, д], [п, ВАЛ_ВЕРХ, п])
    for имя, откуда, куда in список:
        assert not пересекаются(столб, (откуда, куда)), \
            '%s: куб %s залезает в гнездо вала' % (модель, имя)

    # 2. Потолок гнезда есть, и он выше огрызка вала — иначе дыра сквозная.
    потолки = [откуда[1] for имя, откуда, куда in список
               if откуда[0] <= д and куда[0] >= п and откуда[2] <= д and куда[2] >= п
               and откуда[1] >= ВАЛ_ВЕРХ]
    assert потолки, '%s: над гнездом нет сплошной плиты — дыра сквозная' % модель

    # 3. Кубы не налезают друг на друга: совпавшие грани мигают в игре.
    for i, (имя1, о1, к1) in enumerate(список):
        for имя2, о2, к2 in список[i + 1:]:
            assert not пересекаются((о1, к1), (о2, к2)), \
                '%s: кубы %s и %s пересекаются' % (модель, имя1, имя2)

    print('%-18s гнездо %d..%d открыто до y=%.1f, потолок на y=%d, кубов %d'
          % (модель, д, п, ВАЛ_ВЕРХ, min(потолки), len(список)))


if __name__ == '__main__':
    for модель in ('andesite_purifier', 'brass_purifier'):
        проверить(модель)
    print('гнездо вала на месте')
